"""Shared cocotb + Verilator runner for the dv/tests benches.

    run(top="g2d_csr_top_tb", module="test_csr_top", params={...}, tag="d4")

builds rtl/ (all packages + sources) plus dv/tb/<top>.sv when it exists (otherwise, for a top named
<module>_tb, a wrapper generated by tbwrap.py) and the dv/sva checkers, with -Wall and rtl/lint.vlt,
into build/dv/<top>[_<tag>], then runs the cocotb module. SEED and WAVES come from the environment.
`sources` replaces the source list (small benches of single blocks).

Hooks for scripts/regress.py (parallel runs must not share a build or a result file):
  G2D_BUILD_DIR_FILE=<file>  append the build directory to <file> and return (no build, no run)
  G2D_BUILD_ONLY=1           build and return
  G2D_SKIP_BUILD=1           run the existing build
Result files are named per seed and process, so runs of one build may run in parallel.
G2D_CODE_COV=1: line and toggle coverage of rtl/ (dv/sva/coverage.vlt switches it off elsewhere), built
into <build_dir>_cov; each run writes build/coverage/code/dat/<module>_<tag>_s<seed>_<pid>.dat
(scripts/code_coverage.py merges and reports them).
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT / "scripts") not in sys.path:
    sys.path.insert(0, str(ROOT / "scripts"))

PKGS = [
    ROOT / "rtl/pkg/generated/g2d_csr_pkg.sv",
    ROOT / "rtl/pkg/generated/g2d_state_pkg.sv",
    ROOT / "rtl/pkg/generated/g2d_gamma_pkg.sv",
    ROOT / "rtl/pkg/g2d_pkg.sv",
]
RTL_DIRS = ["common", "csr", "axi", "cmdproc", "fill", "blend", "blit", "raster", "gradient", "pix", "cdc", "adapt", "top",
            "wrap/generated"]


def rtl_sources() -> list[Path]:
    srcs = [ROOT / "rtl/csr/generated/g2d_csr_regs.sv"]
    for d in RTL_DIRS:
        srcs += sorted((ROOT / "rtl" / d).glob("*.sv"))
    return srcs


def cov_dat(module: str, tag: str) -> Path:
    d = ROOT / "build" / "coverage" / "code" / "dat"
    d.mkdir(parents=True, exist_ok=True)
    return d / f"{module}_{tag}_s{os.environ.get('SEED', '1')}_{os.getpid()}.dat"


def run(top: str, module: str, params: dict | None = None, tag: str = "", testcase=None,
        extra_env: dict | None = None, timeout_s: int | None = None, sources: list | None = None,
        defines: dict | None = None, loops: dict | None = None, extra_build_args: list | None = None,
        with_sva: bool = True) -> None:
    from cocotb_tools.runner import get_results, get_runner

    import gen_regs

    assert gen_regs.main(["--check"]) == 0, "generated register files are stale: run `make regs`"
    import gen_wrappers
    assert gen_wrappers.main(["--check"]) == 0, "generated wrappers are stale: run `make regs`"
    params = params or {}
    code_cov = os.environ.get("G2D_CODE_COV") == "1"
    build_dir = ROOT / "build" / "dv" / ((f"{top}_{tag}" if tag else top) + ("_cov" if code_cov else ""))
    if os.environ.get("G2D_BUILD_DIR_FILE"):
        with open(os.environ["G2D_BUILD_DIR_FILE"], "a") as f:
            f.write(f"{build_dir}\n")
        return
    tb = ROOT / "dv/tb" / f"{top}.sv"
    if not tb.exists() and top.endswith("_tb"):
        # generated wrapper (ports without _i/_o suffixes) around the RTL module of the same name
        import tbwrap
        mod = top[:-3]
        src = next(p for p in rtl_sources() if p.stem == mod)
        tb = tbwrap.write(src, mod, ROOT / "build" / "dv" / "tb", loops)
    # simulation-only checkers (dv/sva): bound into the RTL wherever their target modules exist
    # (with_sva=False: a gate-level netlist has none of the RTL modules the checkers bind to)
    sva = (sorted((ROOT / "dv" / "sva").glob("g2d_*_sva.sv")) + [ROOT / "dv" / "sva" / "g2d_binds.sv"]) if with_sva else []
    if sources is None:
        sources = PKGS + rtl_sources() + ([tb] if tb.exists() else []) + sva
    else:
        sources = list(sources) + sva
    waves = bool(int(os.environ.get("WAVES", "0")))
    runner = get_runner("verilator")
    # make jobs of one Verilator build (cocotb default 4); scripts/regress.py lowers it when it builds in
    # parallel so that the total stays within the core budget
    import cocotb_tools.runner as ctr
    ctr.MAX_PARALLEL_BUILD_JOBS = int(os.environ.get("G2D_BUILD_JOBS", "4"))
    if os.environ.get("G2D_SKIP_BUILD") != "1":
        runner.build(
            sources=sources,
            hdl_toplevel=top,
            parameters=params,
            defines=defines or {},
            build_dir=build_dir,
            # X sources (non-reset flops, X assignments) get random values at run time (plusarg below), so
            # a missing reset or a read of uninitialised data shows up as a mismatch, not as a lucky 0.
            build_args=["-Wall", str(ROOT / "rtl/lint.vlt"), str(ROOT / "dv/sva/sva.vlt"), "-O3", "--x-assign",
                        "unique", "--x-initial", "unique", "--assert"] +
                       (["--coverage-line", "--coverage-toggle", str(ROOT / "dv/sva/coverage.vlt")] if code_cov else []) +
                       (["-Wno-fatal"] if os.environ.get("G2D_NO_FATAL") == "1" else []) +  # mutants (scripts/mutate.py)
                       list(extra_build_args or []),
            timescale=("1ns", "1ps"),
            waves=waves,
        )
    else:
        # state build() would set (cocotb_tools runner), without compiling
        runner._set_verilog_sources([])
        runner._set_vhdl_sources([])
        runner._set_sources(sources)
        runner._set_build_args([])
        runner.hdl_toplevel = top
        runner.parameters = dict(params)
        runner.build_dir = build_dir
        runner.waves = waves
    if os.environ.get("G2D_BUILD_ONLY") == "1":
        return
    # functional coverage file per process: several nodes may share a build and run at the same time
    env = {"G2D_ROOT": str(ROOT), "G2D_COV_NAME": f"{module}_{tag or top}_{os.getpid()}",
           **{k: str(v) for k, v in (extra_env or {}).items()}}
    env.update({f"G2D_P_{k}": str(v) for k, v in params.items()})
    model = Path(os.environ.get("G2D_MODEL_PATH", ROOT / "build" / "model")).resolve()
    paths = [str(ROOT / "dv/common"), str(ROOT / "scripts"), str(model)]
    env["PYTHONPATH"] = os.pathsep.join(paths + [p for p in os.environ.get("PYTHONPATH", "").split(os.pathsep) if p])
    xml = runner.test(
        hdl_toplevel=top,
        test_module=module,
        testcase=testcase,
        test_dir=ROOT / "dv/tests",
        build_dir=build_dir,
        results_xml=str(build_dir / f"results_{module}_s{os.environ.get('SEED', '1')}_{os.getpid()}.xml"),
        seed=os.environ.get("SEED"),
        extra_env=env,
        plusargs=["+verilator+rand+reset+2", f"+verilator+seed+{int(os.environ.get('SEED', '1')) + 1}"] +
                 ([f"+verilator+coverage+file+{cov_dat(module, tag or top)}"] if code_cov else []),
        waves=waves,
    )
    total, failed = get_results(xml)
    assert total > 0 and failed == 0, f"{failed}/{total} cocotb tests failed"
