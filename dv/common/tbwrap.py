"""Generate a cocotb wrapper for an RTL module: same parameters, ports renamed without the _i/_o/_ni
suffix (clk_i -> clk, *_ni -> *_n), so cocotbext-axi and our AXI memory model find the channels
by prefix (s_axil_*, m_axi_*).

The wrapper is written to build/dv/tb/<module>_tb.sv (generated, not committed). Supported port style
(the project RTL style): one `input|output logic [...] name,` declaration per line.
"""

from __future__ import annotations

import re
from pathlib import Path

PORT_RE = re.compile(r"^\s*(input|output)\s+logic\s*((?:\[[^\]]+\]\s*)*)(\w+)\s*,?\s*(//.*)?$")


def _balanced(text: str, start: int) -> int:
    """Index just after the parenthesis group that opens at text[start] == '('."""
    depth = 0
    for i in range(start, len(text)):
        if text[i] == "(":
            depth += 1
        elif text[i] == ")":
            depth -= 1
            if depth == 0:
                return i + 1
    raise ValueError("unbalanced parentheses")


def rename(port: str) -> str:
    if port.endswith("_ni"):
        return port[:-1]          # rst_ni -> rst_n, rst_cfg_ni -> rst_cfg_n
    return re.sub(r"_(i|o)$", "", port)


def wrapper(src: Path, module: str, loops: dict | None = None) -> str:
    """loops: {input port: output port} connected inside the wrapper (e.g. AHB HREADY = HREADYOUT); the input is
    then not a port of the wrapper."""
    loops = loops or {}
    text = src.read_text()
    m = re.search(rf"\bmodule\s+{module}\b", text)
    if not m:
        raise ValueError(f"module {module} not found in {src}")
    pos = m.end()
    # imports between the module name and the parameter/port list
    head_end = text.index("(", pos)
    imports = text[pos:head_end]
    params = ""
    if imports.rstrip().endswith("#"):
        imports = imports.rstrip()[:-1]
        pend = _balanced(text, head_end)
        params = text[head_end:pend]
        pstart = text.index("(", pend)
    else:
        pstart = head_end
    plist = text[pstart:_balanced(text, pstart)]
    ports = []
    for line in plist.splitlines():
        pm = PORT_RE.match(line)
        if pm:
            ports.append((pm.group(1), pm.group(2).strip(), pm.group(3)))
    if not ports:
        raise ValueError(f"no ports parsed for {module}")
    decl = ",\n".join(f"  {d:6} logic {w:24} {rename(n)}" for d, w, n in ports if n not in loops)
    conn = ",\n".join(f"    .{n} ({rename(loops.get(n, n))})" for d, w, n in ports)
    pnames = re.findall(r"parameter\s+(?:int\s+unsigned|int|bit|logic(?:\s*\[[^\]]*\])?)\s+(\w+)", params)
    pass_params = (" #(\n" + ",\n".join(f"    .{p}({p})" for p in pnames) + "\n  )") if pnames else ""
    return (f"// GENERATED by dv/common/tbwrap.py from {src.name}. DO NOT EDIT.\n\n"
            f"module {module}_tb{imports.rstrip()}\n" + (f"#{params}" if params else "") + "\n(\n" + decl + "\n);\n\n"
            f"  {module}{pass_params} u_dut (\n" + conn + "\n  );\n\nendmodule\n")


def write(src: Path, module: str, out_dir: Path, loops: dict | None = None) -> Path:
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / f"{module}_tb.sv"
    text = wrapper(src, module, loops)
    if not out.exists() or out.read_text() != text:
        out.write_text(text)
    return out
