"""g2d_top through LibreLane on IHP SG13G2 (v2.0 step C, docs/ASIC.md).

  asic_ihp.py synth  --tag T --period NS            sv2v + LibreLane up to the synthesis checks
  asic_ihp.py pnr    --tag T --from-synth S --period NS [--util PCT] [--density PCT]
                                                     floorplan with generated macro placement, place, CTS, route,
                                                     signoff (STA in three corners, DRC, LVS) from synthesis run S
  asic_ihp.py resume --tag T                        continue an interrupted pnr from its first unfinished step
                                                     (new run pnr_rN started from the last finished step's state)
  asic_ihp.py prune  --tag T                        delete step views (odb, def, netlists, parasitics) that the
                                                     latest finished state no longer references (disk)
  asic_ihp.py sta    --tag T --period NS [--corner typ|slow|fast] [--in-frac F --out-frac F]
                                                     signoff timing of the routed design, one corner per OpenSTA run
                                                     (syn/ihp/sta_signoff.tcl; needs RCX done): all paths and
                                                     register-to-register, reports in build/asic/ihp/<T>/sta/<corner>
  asic_ihp.py report --tag T                        area, cells, macros, per-corner slack and fmax, DRC / LVS

Inputs: the RTL file list of the Makefile (RTL_PKGS, RTL_SRCS_NO_RAM) with the IHP memory variant rtl/ram/ihp
(g2d_ram_1r1w / g2d_ram_sp on the PDK's SRAM macros), converted to Verilog-2005 by sv2v (Yosys 0.62 has no
SystemVerilog frontend for this RTL; the slang plugin is not packaged). Constraints: syn/constraints/g2d_top.sdc with
G2D_CORE_PERIOD = CLOCK_PERIOD. PDN: syn/ihp/pdn_cfg.tcl. Outputs under build/asic/ihp/<tag> (not committed).

Tools (docs/TOOLS.md): LibreLane 3.0.3 (PATH or ~/tools/nix-profiles/librelane/bin), sv2v
(~/tools/nix-profiles/sv2v/bin), IHP-Open-PDK (IHP_PDK_ROOT, default ~/tools/pdk/IHP-Open-PDK) with
libs.ref/sg13g2_sram.
"""

from __future__ import annotations

import argparse
import json
import math
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HOME = Path.home()
PDK_ROOT = Path(os.environ.get("IHP_PDK_ROOT", HOME / "tools/pdk/IHP-Open-PDK"))
SRAM = PDK_ROOT / "ihp-sg13g2/libs.ref/sg13g2_sram"
OUT = ROOT / "build/asic/ihp"
TOOL_PATHS = [HOME / "tools/nix-profiles/librelane/bin", HOME / "tools/nix-profiles/sv2v/bin"]
# timing corners of the PDK's LibreLane config -> SRAM liberty corner (no -40 C SRAM view: -55 C is used)
CORNERS = {"*_typ_1p20V_25C": "typ_1p20V_25C", "*_slow_1p08V_125C": "slow_1p08V_125C",
           "*_fast_1p32V_m40C": "fast_1p32V_m55C"}
SITE_W, ROW_H = 0.48, 3.78          # sg13g2 core site
# spacing between macros. X: twice the macro halo (FP_MACRO_*_HALO = 10), so no standard-cell row sliver remains
# between macro columns (a vertical sliver gets no power strap: PDN-0179 "unable to repair all channels").
# Y: every SRAM has all signal pins on its bottom edge (Metal2), facing the macro below in a column: a 45 um channel
# (12 rows, crossed by the TopMetal1 straps) lets them escape; 15 um gave a global route that did not converge.
MACRO_GAP_X, MACRO_GAP_Y = 20.16, 45.36
EDGE = 40.0                          # die edge to core / macros (core ring, IO pins)
STRIP_MIN = 250.0                    # narrowest standard-cell strip between macro blocks
BLOCK_H = 1900.0                     # tallest macro block (16 x (74.87 + 45.36) = one cache bank)
BAND = 200.0                         # standard-cell band between tiers of blocks


def tool(name: str) -> str:
    for p in TOOL_PATHS:
        if (p / name).exists():
            return str(p / name)
    w = shutil.which(name)
    if not w:
        sys.exit(f"error: {name} not found (docs/TOOLS.md)")
    return w


def rtl_files() -> list[str]:
    mk = OUT / "print.mk"
    mk.parent.mkdir(parents=True, exist_ok=True)
    mk.write_text("p:\n\t@echo $(RTL_PKGS) $(RTL_SRCS_NO_RAM)\n")
    out = subprocess.run(["make", "-s", "-f", "Makefile", "-f", str(mk), "p"], cwd=ROOT, check=True, text=True,
                         capture_output=True).stdout.split()
    return out + [f"rtl/ram/ihp/{n}.sv" for n in ("g2d_ram_1r1w", "g2d_ram_sp", "g2d_ihp_2p", "g2d_ihp_1p")]


def convert(src_dir: Path) -> Path:
    src_dir.mkdir(parents=True, exist_ok=True)
    out = src_dir / "g2d_top.v"
    r = subprocess.run([tool("sv2v"), "-DSYNTHESIS", "--top=g2d_top", *rtl_files()], cwd=ROOT, text=True,
                       capture_output=True)
    if r.returncode != 0:
        sys.exit(f"sv2v failed:\n{r.stderr}")
    out.write_text("// GENERATED by scripts/asic_ihp.py with sv2v from the RTL file list. DO NOT EDIT.\n" + r.stdout)
    return out


def sdc(src_dir: Path, io_frac: float | None = None, macro_hold: float = 0.0) -> Path:
    """Implementation SDC: the project template plus, for place and route only, extra hold uncertainty at the SRAM
    macros (the paths that violated hold after routing; signoff uses the template alone, `asic_ihp.py sta`)."""
    p = src_dir / "g2d_top_librelane.sdc"
    io = f"set G2D_IN_FRAC {io_frac}\nset G2D_OUT_FRAC {io_frac}\n" if io_frac is not None else ""
    mh = (f"set_clock_uncertainty -hold {macro_hold + 0.05} [get_pins {{*u_macro/A_CLK *u_macro/B_CLK}}]\n"
          if macro_hold else "")
    p.write_text("# GENERATED by scripts/asic_ihp.py\nset G2D_CORE_PERIOD $::env(CLOCK_PERIOD)\n" + io +
                 f"source {ROOT / 'syn/constraints/g2d_top.sdc'}\n" + mh)
    return p


def macro_names(verilog: Path) -> set[str]:
    return set(re.findall(r"\b(RM_IHPSG13_\w+)\s+(?:#\s*\(|\\?[\w.\[\]$]+\s*\()", verilog.read_text()))


def macro_size(name: str) -> tuple[float, float]:
    m = re.search(r"^\s*SIZE\s+([\d.]+)\s+BY\s+([\d.]+)", (SRAM / "lef" / f"{name}.lef").read_text(), re.M)
    return float(m.group(1)), float(m.group(2))


def macro_cfg(names, instances=None) -> dict:
    cfg = {}
    for n in sorted(names):
        cfg[n] = {
            "gds": [str(SRAM / "gds" / f"{n}.gds")],
            "lef": [str(SRAM / "lef" / f"{n}.lef")],
            "lib": {k: [str(SRAM / "lib" / f"{n}_{v}.lib")] for k, v in CORNERS.items()},
            "instances": {},
        }
    for inst, (cell, x, y, orient) in (instances or {}).items():
        cfg[cell]["instances"][inst] = {"location": [round(x, 3), round(y, 3)], "orientation": orient}
    return cfg


def base_config(src: Path, sdc_file: Path, period: float, names) -> dict:
    return {
        "DESIGN_NAME": "g2d_top",
        "VERILOG_FILES": [str(src)],
        "CLOCK_PORT": "clk_i",
        "CLOCK_PERIOD": period,
        "PNR_SDC_FILE": str(sdc_file),
        "SIGNOFF_SDC_FILE": str(sdc_file),
        "RUN_LINTER": False,               # the RTL is linted by `make lint` (Verilator -Wall)
        # per-module synthesis, flattened afterwards: the flat run peaked at 7 GB (600 k cells before mapping)
        "SYNTH_HIERARCHY_MODE": "deferred_flatten",
        "MACROS": macro_cfg(names),
        "PDN_MACRO_CONNECTIONS": [".*u_macro VPWR VGND VDD! VSS!", ".*u_macro VPWR VGND VDDARRAY! VSS!"],  # PDK nets
        "PDN_CFG": str(ROOT / "syn/ihp/pdn_cfg.tcl"),
        "DRT_THREADS": 8,
        "STA_THREADS": 8,
        "KLAYOUT_DRC_THREADS": 8,
    }


def run_librelane(design_dir: Path, run_tag: str, extra: list[str]) -> int:
    cmd = [tool("librelane"), "--manual-pdk", "--pdk-root", str(PDK_ROOT), "--pdk", "ihp-sg13g2", "--scl",
           "sg13g2_stdcell", "--run-tag", run_tag, "--overwrite", "--hide-progress-bar", "-j", "8", *extra,
           str(design_dir / "config.json")]
    log = design_dir / f"{run_tag}.log"
    print(f"librelane: {' '.join(cmd)}\n  log {log}")
    with open(log, "w") as f:
        return subprocess.run(cmd, cwd=design_dir, stdout=f, stderr=subprocess.STDOUT).returncode


def step_dir(run: Path, pattern: str) -> Path:
    ds = sorted(d for d in run.iterdir() if d.is_dir() and re.fullmatch(r"\d+-" + pattern, d.name))
    if not ds:
        sys.exit(f"error: no step {pattern} in {run}")
    return ds[-1]


# ---------------------------------------------------------------- synthesis
def cmd_synth(a) -> int:
    d = OUT / a.tag
    src = convert(d / "src")
    names = macro_names(src)
    cfg = base_config(src, sdc(d / "src"), a.period, names)
    (d / "config.json").write_text(json.dumps(cfg, indent=2) + "\n")
    rc = run_librelane(d, "synth", ["-T", "Checker.NetlistAssignStatements"])
    print(f"synth rc={rc}")
    return rc


# ---------------------------------------------------------------- floorplan
def instances_from_netlist(nl: Path) -> list[tuple[str, str]]:
    out = []
    for m in re.finditer(r"^\s*(RM_IHPSG13_\w+)\s+(\\\S+|\S+)\s*\(", nl.read_text(), re.M):
        out.append((m.group(2).lstrip("\\"), m.group(1)))
    return out


def place_macros(insts, std_area: float, util: float):
    """Macro blocks in a grid, separated by standard-cell strips (vertical) and bands (horizontal). Returns die
    (w, h) and {instance: (cell, x, y, orientation)}.

    Every SRAM has all its signal pins on the bottom edge, so a macro's ~80 nets leave sideways through the 45 um
    channel under it. What did not route (docs/ASIC.md "Floorplan"):
      - macro columns side by side: their nets add up on the way to the logic, the global route detours over the
        macros where only TopMetal1 is free;
      - one die-high column per group with strips between: the texture cache's 4 x 512 read-data wires run along
        the column edges to the cache logic, 12 000 shorts on two lines at the column's edges.
    So a block is at most BLOCK_H high (16 of the 64x32 macros = one cache bank), blocks are placed in tiers with
    a strip on both sides and a band between tiers: every bank is a compact block with logic all around it."""
    sizes = {c: macro_size(c) for _, c in insts}
    by_cell: dict[str, list[str]] = {}
    # the texture cache's data macros first (4 banks x 16 macros of one cell type: one block per bank)
    for i, c in sorted(insts, key=lambda ic: (".u_cache.g_bank" not in ic[0], ic[0])):
        by_cell.setdefault(c, []).append(i)
    blocks, cur, used = [], [], 0.0                       # a block: [(instance, cell, y offset)]
    cache_first = lambda c: not any(".u_cache.g_bank" in i for i in by_cell[c])
    for c in sorted(by_cell, key=lambda c: (cache_first(c), -sizes[c][0], c)):
        for i in by_cell[c]:
            if cur and used + sizes[c][1] > BLOCK_H:
                blocks.append(cur)
                cur, used = [], 0.0
            cur.append((i, c, used))
            used += sizes[c][1] + MACRO_GAP_Y
    if cur:
        blocks.append(cur)
    widths = [max(sizes[c][0] for _, c, _ in b) for b in blocks]
    std_need = std_area / util
    best = None
    for tiers in range(1, len(blocks) + 1):
        per = math.ceil(len(blocks) / tiers)
        rows = [list(range(k, min(k + per, len(blocks)))) for k in range(0, len(blocks), per)]
        tiers_n = len(rows)
        band_area_w = max(sum(widths[b] for b in r) for r in rows)
        strip = max(STRIP_MIN, std_need / (tiers_n * BLOCK_H) / (per + 1))
        w = band_area_w + (per + 1) * strip + 2 * EDGE
        h = tiers_n * BLOCK_H + (tiers_n + 1) * BAND + 2 * EDGE
        score = max(w, h) / min(w, h) * w * h
        if best is None or score < best[0]:
            best = (score, w, h, rows, strip)
    _, w, h, rows, strip = best
    snap = lambda v, g: math.floor(v / g) * g
    w, h = math.ceil(w / 10) * 10, math.ceil(h / 10) * 10
    place = {}
    y = EDGE + BAND
    for r in rows:
        x = EDGE + strip
        for b in r:
            for i, c, yo in blocks[b]:
                place[i] = (c, snap(x, SITE_W), snap(y + yo, ROW_H), "N")
            x += widths[b] + strip
        y += BLOCK_H + BAND
    return (w, h), place


def std_cell_area(synth_run: Path) -> float:
    st = step_dir(synth_run, "yosys-synthesis")
    m = json.loads((st / "state_out.json").read_text())["metrics"]
    total = m.get("design__instance__area") or m.get("design__instance__area__stdcell")
    macro = m.get("design__instance__area__macros", 0) or 0
    std = m.get("design__instance__area__stdcell") or (total - macro)
    return float(std)


def cmd_pnr(a) -> int:
    sd = OUT / a.from_synth
    synth_run = sd / "runs" / "synth"
    st = step_dir(synth_run, "checker-netlistassignstatements")
    nl = next((step_dir(synth_run, "yosys-synthesis")).glob("*.nl.v"))
    insts = instances_from_netlist(nl)
    std = std_cell_area(synth_run)
    (w, h), place = place_macros(insts, std, a.util / 100)
    d = OUT / a.tag
    d.mkdir(parents=True, exist_ok=True)
    src_dir = sd / "src"
    names = {c for _, c in insts}
    cfg = base_config(src_dir / "g2d_top.v", sdc(d, a.io_frac, a.macro_hold), a.period, names)
    cfg["MACROS"] = macro_cfg(names, place)
    # margins of the post-CTS timing repair: its wire estimate is optimistic against the routed design (p20c:
    # hold -0.4 .. -0.5 ns into SRAM pins after routing with the default 0.1 ns margin)
    cfg["PL_RESIZER_HOLD_SLACK_MARGIN"] = a.hold_margin
    cfg["PL_RESIZER_SETUP_SLACK_MARGIN"] = a.setup_margin
    cfg.update({
        "FP_SIZING": "absolute",
        "DIE_AREA": [0, 0, w, h],
        "PL_TARGET_DENSITY_PCT": a.density,
        "FP_MACRO_HORIZONTAL_HALO": 10,
        "FP_MACRO_VERTICAL_HALO": 10,
        "PDN_HORIZONTAL_HALO": 10,
        "PDN_VERTICAL_HALO": 10,
        "GRT_ALLOW_CONGESTION": True,
        "GRT_OVERFLOW_ITERS": 15,
        "DRT_SAVE_DRC_REPORT_ITERS": 1,    # violation locations after every detailed-routing iteration
        # no antenna repair after detailed routing: it runs the global router on top of the detailed router's
        # 12.6 GB and was killed by the 15 GB limit before the routed design was saved (antenna repair at the
        # global-routing stage stays; the remaining violations are reported, docs/ASIC.md)
        "DRT_ANTENNA_REPAIR_ITERS": 0,          # bound the overflow clean-up (50 ran > 5 h on the first floorplan)
        "PL_RESIZER_ALLOW_SETUP_VIOS": True,
        # repair buffers on wires over the macro columns (up to ~700 um wide) must be able to move off them
        "PL_MAX_DISPLACEMENT_X": 1500,
        "PL_MAX_DISPLACEMENT_Y": 1500,
    })
    (d / "config.json").write_text(json.dumps(cfg, indent=2) + "\n")
    print(f"pnr {a.tag}: {len(insts)} macros, std cells {std / 1e6:.2f} mm2, die {w:.0f} x {h:.0f} um "
          f"({w * h / 1e6:.2f} mm2), period {a.period} ns")
    skip = [x for s in (a.skip or []) for x in ("-S", s)]
    rc = run_librelane(d, "pnr", ["-F", "OpenROAD.CheckSDCFiles", "-i", str(st / "state_out.json"), *skip])
    print(f"pnr rc={rc}")
    return rc


# ---------------------------------------------------------------- resume
def pnr_runs(d: Path) -> list[Path]:
    """pnr, pnr_r1, pnr_r2, ... in order."""
    rs = [r for r in (d / "runs").glob("pnr*") if re.fullmatch(r"pnr(_r\d+)?", r.name)]
    return sorted(rs, key=lambda r: int(r.name[5:]) if "_r" in r.name else 0)


def finished_steps(run: Path) -> list[Path]:
    """Step directories of a run up to the first one without a state_out.json (index order)."""
    ds = sorted((p for p in run.iterdir() if p.is_dir() and re.match(r"\d+-", p.name)),
                key=lambda p: int(p.name.split("-")[0]))
    out = []
    for p in ds:
        if not (p / "state_out.json").exists():
            break
        out.append(p)
    return out


def cmd_resume(a) -> int:
    d = OUT / a.tag
    runs = pnr_runs(d)
    if not runs:
        sys.exit(f"error: no pnr run in {d}")
    run = runs[-1]
    if (run / "final" / "metrics.json").exists():
        print(f"{run.name} is complete")
        return 0
    done = finished_steps(run)
    # step directories are created in the order of the flow log's "Running '<id>'" lines (skipped steps get none)
    ids = re.findall(r"Running '([\w.-]+)'", (run / "flow.log").read_text())
    if not done or (not a.from_step and len(ids) <= len(done)):
        sys.exit(f"error: cannot tell the next step of {run} ({len(done)} finished, {len(ids)} started)")
    nxt, state = a.from_step or ids[len(done)], done[-1] / "state_out.json"
    tag = f"pnr_r{len(runs)}"
    skip = [x for s in (a.skip or []) for x in ("-S", s)]
    print(f"resume {a.tag}: {run.name} finished {done[-1].name}; {tag} from {nxt}" + (f", skip {a.skip}" if skip else ""))
    rc = run_librelane(d, tag, ["-F", nxt, "-i", str(state), *skip])
    print(f"resume rc={rc}")
    return rc


# ---------------------------------------------------------------- prune
HEAVY = (".odb", ".def", ".nl.v", ".pnl.v", ".spef", ".sdf", ".gds", ".mag", ".klayout.gds", ".v")


def state_paths(x) -> set[str]:
    if isinstance(x, str):
        return {x}
    if isinstance(x, dict):
        return set().union(*(state_paths(v) for k, v in x.items() if k != "metrics")) if x else set()
    if isinstance(x, list):
        return set().union(*(state_paths(v) for v in x)) if x else set()
    return set()


def cmd_prune(a) -> int:
    d = OUT / a.tag
    runs = pnr_runs(d)
    if not runs:
        return 0
    last = runs[-1]
    done = finished_steps(last)
    if not done:
        return 0
    keep = state_paths(json.loads((done[-1] / "state_out.json").read_text()))
    freed = 0
    for run in runs:
        steps = finished_steps(run)
        if run == last:
            steps = steps[:-1]          # the latest finished step stays whole
        for sd in steps:
            for f in sd.iterdir():
                if f.is_file() and f.name.endswith(HEAVY) and str(f) not in keep:
                    freed += f.stat().st_size
                    f.unlink()
    print(f"prune {a.tag}: freed {freed / 2**30:.2f} GB")
    return 0


# ---------------------------------------------------------------- signoff timing, one corner at a time
STA_CORNERS = {"typ": ("typ_1p20V_25C", "typ_1p20V_25C"), "slow": ("slow_1p08V_125C", "slow_1p08V_125C"),
               "fast": ("fast_1p32V_m40C", "fast_1p32V_m55C")}          # (standard cells, SRAM)


def latest_state(d: Path) -> dict:
    for run in reversed(pnr_runs(d)):
        st = finished_steps(run)
        if st:
            return json.loads((st[-1] / "state_out.json").read_text())
    sys.exit(f"error: no finished step in {d}")


def cmd_sta(a) -> int:
    d = OUT / a.tag
    st = latest_state(d)
    spef = next(iter(st["spef"].values())) if isinstance(st.get("spef"), dict) else st.get("spef")
    if not spef or not st.get("nl"):
        sys.exit("error: the latest state has no netlist / SPEF (run the flow up to OpenROAD.RCX)")
    names = macro_names(Path(st["nl"]))
    sta = shutil.which("sta") or str(HOME / "tools/opensta/bin/sta")
    rc = 0
    for corner in (a.corner or ["typ", "slow", "fast"]):
        std, sram = STA_CORNERS[corner]
        libs = [str(PDK_ROOT / f"ihp-sg13g2/libs.ref/sg13g2_stdcell/lib/sg13g2_stdcell_{std}.lib")]
        libs += [str(SRAM / "lib" / f"{n}_{sram}.lib") for n in sorted(names)]
        out = d / "sta" / (corner + (a.suffix or ""))
        out.mkdir(parents=True, exist_ok=True)
        env = dict(os.environ, G2D_STA_NETLIST=st["nl"], G2D_STA_SPEF=spef, G2D_STA_LIBS=" ".join(libs),
                   G2D_STA_PERIOD=str(a.period), G2D_STA_OUT=str(out),
                   G2D_SDC=str(ROOT / "syn/constraints/g2d_top.sdc"))
        if a.in_frac is not None:
            env["G2D_STA_IN_FRAC"] = str(a.in_frac)
        if a.out_frac is not None:
            env["G2D_STA_OUT_FRAC"] = str(a.out_frac)
        with open(out / "sta.log", "w") as f:
            r = subprocess.run([sta, "-no_splash", "-exit", str(ROOT / "syn/ihp/sta_signoff.tcl")], env=env, stdout=f,
                               stderr=subprocess.STDOUT)
        def worst(rpt, group="g2d_core"):
            """worst slack (ns) of a path group in a report_checks file"""
            vals = []
            for blk in (out / rpt).read_text().split("Startpoint: ")[1:]:
                g = re.search(r"Path Group: (\S+)", blk)
                s = re.search(r"(-?[\d.]+)\s+slack", blk)
                if g and s and g.group(1) == group:
                    vals.append(float(s.group(1)))
            return min(vals) if vals else None
        try:
            ws = {k: worst(f) for k, f in [("setup_all", "setup_all.rpt"), ("hold_all", "hold_all.rpt"),
                                            ("setup_reg2reg", "setup_reg2reg.rpt"), ("hold_reg2reg", "hold_reg2reg.rpt")]}
            rec = worst("setup_all.rpt", "asynchronous")
            fm = lambda s: f"{1000 / (a.period - s):.1f} MHz" if s is not None else "-"
            print(f"{corner}: rc={r.returncode} period {a.period} ns | setup all {ws['setup_all']} ns ({fm(ws['setup_all'])}), "
                  f"reg2reg {ws['setup_reg2reg']} ns ({fm(ws['setup_reg2reg'])}) | hold all {ws['hold_all']} ns, "
                  f"reg2reg {ws['hold_reg2reg']} ns | recovery {rec} ns")
            (out / "summary.json").write_text(json.dumps(dict(ws, recovery=rec, period=a.period), indent=1) + "\n")
        except OSError as e:
            print(f"{corner}: rc={r.returncode} no reports ({e})")
        rc |= r.returncode
    return rc


# ---------------------------------------------------------------- report
def cmd_report(a) -> int:
    d = OUT / a.tag
    runs = pnr_runs(d)
    cfg = json.loads((d / "config.json").read_text())
    done = [r for r in runs if (r / "final" / "metrics.json").exists()]
    if done:
        m = json.loads((done[-1] / "final" / "metrics.json").read_text())
        print(f"(final metrics of {done[-1].name})")
    else:
        st = finished_steps(runs[-1])
        m = json.loads((st[-1] / "state_out.json").read_text())["metrics"]
        print(f"(no final metrics; last finished step {runs[-1].name}/{st[-1].name})")
    period = float(cfg["CLOCK_PERIOD"])
    print(f"period {period} ns ({1000 / period:.1f} MHz), die {cfg['DIE_AREA'][2]} x {cfg['DIE_AREA'][3]} um")
    for k in ["design__instance__count", "design__instance__count__stdcell", "design__instance__count__macros",
              "design__instance__area", "design__instance__area__stdcell", "design__instance__area__macros",
              "design__instance__utilization", "route__drc_errors", "magic__drc_error__count",
              "klayout__drc_error__count", "design__lvs_error__count", "antenna__violating__nets",
              "power__total"]:
        if k in m:
            print(f"  {k} = {m[k]}")
    rows = []
    for k, v in sorted(m.items()):
        mm = re.fullmatch(r"timing__(setup|hold)__ws__corner:(\S+)", k)
        if mm:
            rows.append((mm.group(2), mm.group(1), float(v)))
    worst = None
    for corner, kind, ws in rows:
        extra = ""
        if kind == "setup":
            fmax = 1000.0 / (period - ws)
            extra = f"  fmax {fmax:.1f} MHz (1 / (period - slack))"
            worst = fmax if worst is None else min(worst, fmax)
        print(f"  {corner:24s} {kind:5s} worst slack {ws:+.3f} ns{extra}")
    if worst is not None:
        print(f"  all corners: fmax {worst:.1f} MHz")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    s = sub.add_parser("synth")
    s.add_argument("--tag", required=True)
    s.add_argument("--period", type=float, default=10.0)
    p = sub.add_parser("pnr")
    p.add_argument("--tag", required=True)
    p.add_argument("--from-synth", required=True)
    p.add_argument("--period", type=float, default=10.0)
    p.add_argument("--util", type=float, default=30.0, help="standard-cell utilisation of their area, %%")
    # 60 % packed the logic at 50-63 % real density in the die centre: 525 k detailed-routing violations (Metal2 /
    # Metal3 shorts) that did not converge. 35 % spreads the cells over the free area.
    p.add_argument("--density", type=float, default=35.0, help="global placement target density, %%")
    p.add_argument("--skip", action="append", help="step id to skip (repeatable)")
    p.add_argument("--io-frac", type=float, help="I/O budget of the SDC (G2D_IN_FRAC = G2D_OUT_FRAC), default 0.6")
    # 0.8 everywhere added 134 k hold buffers: detailed routing ran out of memory. 0.3 + 0.5 at the SRAM pins.
    p.add_argument("--hold-margin", type=float, default=0.3, help="post-CTS hold repair margin, ns")
    p.add_argument("--macro-hold", type=float, default=0.5, help="extra hold uncertainty at SRAM clock pins, ns")
    p.add_argument("--setup-margin", type=float, default=2.0, help="post-CTS setup repair margin, ns")
    r = sub.add_parser("report")
    r.add_argument("--tag", required=True)
    rs = sub.add_parser("resume")
    rs.add_argument("--tag", required=True)
    rs.add_argument("--from-step", help="step id to start from (default: the first unfinished step)")
    rs.add_argument("--skip", action="append", help="step id to skip (repeatable), e.g. OpenROAD.STAMidPNR: the "
                    "mid-flow STA of this design peaks at 12.6 GB, at the container's limit")
    pr = sub.add_parser("prune")
    pr.add_argument("--tag", required=True)
    s2 = sub.add_parser("sta")
    s2.add_argument("--tag", required=True)
    s2.add_argument("--period", type=float, default=20.0)
    s2.add_argument("--corner", action="append", choices=sorted(STA_CORNERS))
    s2.add_argument("--in-frac", type=float)
    s2.add_argument("--out-frac", type=float)
    s2.add_argument("--suffix", help="report directory suffix, e.g. _io30")
    a = ap.parse_args(argv)
    if not SRAM.is_dir():
        sys.exit(f"error: IHP SRAM library not found: {SRAM}")
    return {"synth": cmd_synth, "pnr": cmd_pnr, "resume": cmd_resume, "prune": cmd_prune, "sta": cmd_sta, "report": cmd_report}[a.cmd](a)


if __name__ == "__main__":
    sys.exit(main())
