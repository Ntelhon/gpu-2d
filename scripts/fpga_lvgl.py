"""LVGL frame for the bare-metal FPGA test (v1.2; Phase 7 exit criterion 3).

Runs an LVGL demo on the host software backend (golden model) with the recorder on (G2D_RECORD, format in
sw/hal/model/g2d_hal_model.h) and turns the recording into data the bare-metal test replays on Cheshire
(sw/apps/baremetal/g2d_fpga_test.c, lvgl_replay):

  <out>/lvgl_rec.bin   the recording (MEM / KICK / SOFT_RESET / CHECK records)
  <out>/g2d_lvgl.S     .incbin of it, the demo name and the frame buffer (address, stride, width, height, bytes per
                       pixel) as symbols g2d_lvgl_rec[_end], g2d_lvgl_name, g2d_lvgl_fb[5]
  <out>/lvgl_fb.raw    the frame buffer as a replay leaves it (last MEM content + the GPU-written CHECK bytes), the
                       reference of the VGA capture (scripts/vga_check.py)
  "LVGL <name> pages=<n> bytes=<n> crc=<crc32>" appended to <out>/expected.txt: CRC-32 over the GPU-written bytes of
  every CHECK page (mask bit set), pages in record order, bytes in address order (what the target prints);
  "VGA crc=<crc32 of lvgl_fb.raw>" as well when the frame is 640x480 RGB565 (the VGA test shows it).

The VG-Lite build of the demo passes CPU pointers as GPU addresses (identity mode), so the demo is the variant
linked at 0x9000_0000 (build/lvgl_chs, `make lvgl-chs`): every page the GPU touches is in Cheshire's DRAM, above
the program (0x8000_0000, 8 MB) and the GPU pool (0x8100_0000, 32 MB), and the replay writes them in place (the
demo runs under `setarch -R`, see below). The recorder writes a MEM record at the first touch of every page, so the target needs no zeroed memory.

Usage: fpga_lvgl.py <out_dir> [--demo widgets] [--variant vg16] [--size 640x480] [--frames 2] [--none]
"""
import argparse
import os
import struct
import subprocess
import sys
import tempfile
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REC_MEM, REC_KICK, REC_SOFT_RESET, REC_CHECK, REC_POST, REC_END = 1, 2, 3, 4, 5, 0xFFFFFFFF
# Addresses the replay may write: Cheshire DRAM above the bare-metal program and the GPU pool.
REPLAY_LO, REPLAY_HI = 0x8400_0000, 0xC000_0000


def parse(d):
    magic, ver = struct.unpack_from("<2I", d, 0)
    if magic != 0x43455232 or ver != 2:
        sys.exit("fpga_lvgl.py: not a version-2 recording")
    pos, out = 8, []
    while True:
        (k,) = struct.unpack_from("<I", d, pos)
        pos += 4
        if k == REC_END:
            return out
        if k == REC_MEM:
            a, n = struct.unpack_from("<2I", d, pos)
            out.append((k, a, d[pos + 8:pos + 8 + n], None))
            pos += 8 + n
        elif k in (REC_CHECK, REC_POST):
            a, n = struct.unpack_from("<2I", d, pos)
            out.append((k, a, d[pos + 8:pos + 8 + n], d[pos + 8 + n:pos + 8 + n + n // 8]))
            pos += 8 + n + n // 8
        elif k == REC_KICK:
            a, n = struct.unpack_from("<2I", d, pos)
            out.append((k, a, n, None))
            pos += 8
        elif k == REC_SOFT_RESET:
            out.append((k, 0, 0, None))
        else:
            sys.exit("fpga_lvgl.py: record kind %d at %d" % (k, pos - 4))


def write_asm(out, name, rec, fb):
    inc = '    .incbin "%s"\n' % rec if rec else ""
    (out / "g2d_lvgl.S").write_text(
        "/* Generated by scripts/fpga_lvgl.py; do not edit. */\n"
        "    .section .rodata.g2d_lvgl, \"a\"\n"
        "    .balign 8\n    .global g2d_lvgl_rec\ng2d_lvgl_rec:\n" + inc +
        "    .global g2d_lvgl_rec_end\ng2d_lvgl_rec_end:\n"
        "    .balign 8\n    .global g2d_lvgl_fb\ng2d_lvgl_fb:\n" +
        "".join("    .word 0x%08x\n" % v for v in fb) +
        "    .global g2d_lvgl_name\ng2d_lvgl_name:\n    .asciz \"%s\"\n" % name)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--demo", default="widgets")
    ap.add_argument("--variant", default="vg16", choices=["vg16", "vg32"])
    ap.add_argument("--size", default="640x480")
    ap.add_argument("--frames", type=int, default=2)
    ap.add_argument("--exe", help="demo binary (default build/lvgl_chs/sw/lvgl_demo_<variant>)")
    ap.add_argument("--none", action="store_true", help="no LVGL frame (empty data, nothing expected)")
    a = ap.parse_args()
    out = Path(a.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    if a.none:
        write_asm(out, "", None, [0, 0, 0, 0, 0])
        print("fpga_lvgl.py: no LVGL frame -> %s" % out)
        return
    exe = Path(a.exe) if a.exe else ROOT / "build" / "lvgl_chs" / "sw" / ("lvgl_demo_" + a.variant)
    if not exe.exists():
        sys.exit("fpga_lvgl.py: %s missing (make lvgl-chs)" % exe)
    w, h = (int(x) for x in a.size.split("x"))
    name = "%s_%s_%dx%d_f%d" % (a.demo, a.variant, w, h, a.frames)
    rec = out / "lvgl_rec.bin"
    with tempfile.TemporaryDirectory() as tmp:
        info = Path(tmp) / "fb.txt"
        # setarch -R: no address randomisation for this process. Linux randomises a 64-bit program's brk start within
        # 1 GB, which would move the heap (and the GPU addresses) out of DRAM; without it the heap follows .bss and
        # the recording is reproducible.
        subprocess.run(["setarch", "-R", str(exe), a.demo, str(w), str(h), str(a.frames), str(Path(tmp) / "f"), "0"],
                       env={**os.environ, "G2D_RECORD": str(rec), "G2D_RECORD_POST": "0", "G2D_FB_INFO": str(info)},
                       check=True, capture_output=True, timeout=1800)
        fbi = dict(x.split("=") for x in info.read_text().split())
        host_frame = (Path(tmp) / ("f_%04d.raw" % a.frames)).read_bytes()
    fb = [int(fbi["addr"], 16), int(fbi["stride"]), int(fbi["w"]), int(fbi["h"]), int(fbi["bpp"])]

    recs = parse(rec.read_bytes())
    lo = min(r[1] for r in recs if r[0] in (REC_MEM, REC_CHECK, REC_KICK))
    hi = max(r[1] + 4096 for r in recs if r[0] in (REC_MEM, REC_CHECK, REC_KICK))
    if lo < REPLAY_LO or hi > REPLAY_HI:
        sys.exit("fpga_lvgl.py: recording touches 0x%08x..0x%08x, outside [0x%08x, 0x%08x)" %
                 (lo, hi, REPLAY_LO, REPLAY_HI))

    # Expected target output, and the memory a replay leaves behind (pages: last MEM content + CHECK bytes).
    crc, nbytes, npages, mem = 0, 0, 0, {}
    for k, addr, data, mask in recs:
        if k == REC_MEM:
            mem[addr] = bytearray(data)
        elif k == REC_CHECK:
            npages += 1
            page = mem.setdefault(addr, bytearray(4096))
            sel = bytearray()
            for i in range(len(data)):
                if mask[i >> 3] >> (i & 7) & 1:
                    sel.append(data[i])
                    page[i] = data[i]
            crc = zlib.crc32(sel, crc)
            nbytes += len(sel)
    fb_addr, stride, fw, fh, bpp = fb
    frame = bytearray()
    for y in range(fh):
        row = bytearray()
        a0 = fb_addr + y * stride
        for off in range(0, fw * bpp):
            p = (a0 + off) & ~0xFFF
            row.append(mem[p][(a0 + off) & 0xFFF] if p in mem else 0)
        frame += row
    (out / "lvgl_fb.raw").write_bytes(bytes(frame))
    same = bytes(frame) == host_frame
    write_asm(out, name, rec, fb)
    with open(out / "expected.txt", "a") as f:
        f.write("LVGL %s pages=%d bytes=%d crc=%08x\n" % (name, npages, nbytes, crc & 0xFFFFFFFF))
        if (fw, fh, bpp, stride) == (640, 480, 2, 1280):
            f.write("VGA crc=%08x\n" % zlib.crc32(bytes(frame)))
    print("fpga_lvgl.py: %s, %d records (%d KB), pages 0x%08x..0x%08x, %d CHECK pages, %d bytes, crc %08x; "
          "frame buffer 0x%08x stride %d %dx%d x%d; replay frame %s the host frame" %
          (name, len(recs), rec.stat().st_size // 1024, lo, hi, npages, nbytes, crc, fb_addr, stride, fw, fh, bpp,
           "equals" if same else "DIFFERS FROM"))


if __name__ == "__main__":
    main()
