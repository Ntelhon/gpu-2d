"""Scene set for the bare-metal FPGA test (Phase 7, sw/apps/baremetal/g2d_fpga_test.c).

Generates vgl_scene scripts with the generators of sw/tests/test_scenes.py (the same kinds test_live.py runs on
the live RTL), runs every script on the host software backend (golden model, build/model/sw/vgl_scene) and
writes:
  <out>/g2d_scenes.c     the scripts as C strings (dump lines name no file: the bare-metal runner prints CRCs)
  <out>/expected.txt     per scene the lines the board must print: "rc ...", "crc <id> <crc32>"
                         ("buf" lines carry GPU addresses, which differ between backends, and are not compared)
  g2d_sweep_delays[]     (v1.2) DRAM-delay sweep steps of the bare-metal test (--sweep; "SWEEP_LIST" in expected.txt)
Usage: fpga_scenes.py <out_dir> [--seed N] [--per-kind N] [--kinds clears,blits,...] [--sweep 0,8,16,32,64]
"""
import argparse
import os
import random
import subprocess
import sys
import tempfile
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "sw" / "tests"))

import test_scenes as ts  # noqa: E402

GENS = {"clears": ts.scene_clears, "blits": ts.scene_blits, "paths": ts.scene_paths,
        "patterns": lambda r: ts.scene_patterns(r)[0], "converted": ts.scene_converted, "strokes": ts.scene_strokes,
        "vectors": ts.scene_vectors, "radial": ts.scene_radial, "imgpaths": ts.scene_image_paths,
        "v16": ts.scene_v16, "v16b": ts.scene_v16b}


def c_string(text):
    out = []
    for line in text.split("\n"):
        out.append('    "' + line.replace("\\", "\\\\").replace('"', '\\"') + '\\n"')
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--per-kind", type=int, default=2)
    ap.add_argument("--kinds", default=",".join(GENS))
    ap.add_argument("--sweep", default="", help="DRAM-delay sweep steps (SoC cycles); empty = no sweep")
    a = ap.parse_args()
    sweep = [int(x) for x in a.sweep.split(",") if x != ""]
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    if not ts.BIN.exists():
        sys.exit("fpga_scenes.py: build the software backend first (make model): %s" % ts.BIN)

    scenes = []                                   # (name, script text, expected lines)
    for kind in a.kinds.split(","):
        rng = random.Random(a.seed * 1000 + list(GENS).index(kind))
        for k in range(a.per_kind):
            sc = GENS[kind](rng)
            with tempfile.TemporaryDirectory() as tmp:
                lines = sc.lines + ["finish"] + [f"dump {i} {tmp}/buf{i}.bin" for i in sc.bufs]
                p = subprocess.run([str(ts.BIN)], input="\n".join(lines) + "\n", capture_output=True, text=True,
                                   env={**os.environ, "G2D_MODEL_ARENA_MB": "16"}, timeout=600)
                if p.returncode:
                    sys.exit("fpga_scenes.py: %s %d failed on the software backend:\n%s" % (kind, k, p.stderr))
                exp = [ln for ln in p.stdout.splitlines() if ln.startswith("rc ")]
                # the board prints the CRCs right after the last rc line of the script (dumps come last)
                exp += ["crc %d %08x" % (i, zlib.crc32(Path(f"{tmp}/buf{i}.bin").read_bytes())) for i in sc.bufs]
            script = sc.lines + ["finish"] + [f"dump {i} -" for i in sc.bufs]
            scenes.append((f"{kind}_{k}", "\n".join(script), exp))

    with open(out / "g2d_scenes.c", "w") as f:
        f.write("/* Generated by scripts/fpga_scenes.py (seed %d); do not edit. */\n" % a.seed)
        for n, (name, text, _) in enumerate(scenes):
            f.write("static const char s%d[] =\n%s;\n" % (n, c_string(text)))
        f.write("const char *const g2d_scenes[] = {%s};\n" % ", ".join("s%d" % n for n in range(len(scenes))))
        f.write("const char *const g2d_scene_names[] = {%s};\n" % ", ".join('"%s"' % s[0] for s in scenes))
        f.write("const unsigned g2d_nscenes = %d;\n" % len(scenes))
        f.write("const unsigned g2d_sweep_delays[] = {%s};\n" % ", ".join(str(d) for d in (sweep or [0])))
        f.write("const unsigned g2d_nsweep = %d;\n" % len(sweep))
    with open(out / "expected.txt", "w") as f:
        if sweep:
            f.write("SWEEP_LIST %s\n" % ",".join(str(d) for d in sweep))
        for n, (name, _, exp) in enumerate(scenes):
            f.write("SCENE %d %s\n" % (n, name))
            for ln in exp:
                f.write(ln + "\n")
    print("fpga_scenes.py: %d scenes -> %s" % (len(scenes), out))


if __name__ == "__main__":
    main()
