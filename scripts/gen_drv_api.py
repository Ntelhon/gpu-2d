"""Generate the vg_lite driver's thread-safe API layer (v2.0, audit C-1, docs/PROGRAMMING.md §6.1):

  sw/driver/vg_lite/drv_api.h   renames every public vg_lite_* function the driver implements to drv__vg_lite_*
                                (included by vg_lite_drv.h before vg_lite.h, so the driver's own definitions,
                                prototypes and internal calls use the internal names)
  sw/driver/vg_lite/drv_api.c   the public functions: g2d_hal_lock(), call drv__<name>, g2d_hal_unlock()

Public = declared in sw/include/vg_lite.h or vg_lite_g2d.h AND defined in sw/driver/vg_lite/drv_*.c. An API call
made by the driver itself therefore never takes the lock twice. The lock hooks are weak no-ops in drv_core.c; an
RTOS / OS backend provides real ones (sw/hal/g2d_hal.h).

  gen_drv_api.py [--check]
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import spdx  # noqa: E402

DRV = ROOT / "sw/driver/vg_lite"
HEADERS = [ROOT / "sw/include/vg_lite.h", ROOT / "sw/include/vg_lite_g2d.h"]
BANNER = "/* GENERATED by scripts/gen_drv_api.py from sw/include/vg_lite.h, vg_lite_g2d.h and the driver sources. DO NOT EDIT. */"

DECL_RE = re.compile(r"(?:^|[;{}]|\n)\s*((?:const\s+)?[A-Za-z_]\w*(?:\s*\*)*)\s+(\*?\s*vg_lite_\w+)\s*\(([^;{}()]*)\)\s*;")


def strip_comments(t: str) -> str:
    t = re.sub(r"/\*.*?\*/", " ", t, flags=re.S)
    return re.sub(r"//[^\n]*", "", t)


def declarations():
    out = {}
    for h in HEADERS:
        t = strip_comments(h.read_text())
        t = re.sub(r"^\s*#.*$", "", t, flags=re.M)
        for m in DECL_RE.finditer(t):
            ret, name, args = m.group(1).strip(), m.group(2).replace(" ", ""), " ".join(m.group(3).split())
            if ret in ("typedef", "return"):
                continue
            if name.startswith("*"):
                ret, name = ret + " *", name[1:]
            out.setdefault(name, (ret, args))
    return out


def implemented():
    names = set()
    for f in sorted(DRV.glob("drv_*.c")):
        if f.name == "drv_api.c":
            continue
        t = strip_comments(f.read_text())
        names |= set(re.findall(r"\b(vg_lite_\w+)\s*\([^;{}]*\)\s*\{", t))
    return names


def arg_names(args: str):
    if args in ("", "void", "vg_lite_void"):
        return []
    out = []
    for a in args.split(","):
        a = re.sub(r"\[[^\]]*\]", "", a).strip()
        out.append(re.findall(r"\w+", a)[-1])
    return out


def outputs():
    decl = declarations()
    impl = implemented()
    funcs = sorted(n for n in decl if n in impl)
    h = [BANNER, "#ifndef DRV_API_H", "#define DRV_API_H", "/* public name -> internal implementation (drv_api.c wraps them) */"]
    h += [f"#define {n} drv__{n}" for n in funcs]
    h += ["#endif", ""]
    c = [BANNER, "/* Thread-safe public entry points: one HAL lock around each call (C-1). */",
         '#include "g2d_hal.h"', '#include "vg_lite.h"', '#include "vg_lite_g2d.h"', ""]
    for n in funcs:
        ret, args = decl[n]
        c.append(f"extern {ret} drv__{n}({args or 'void'});")
    c.append("")
    for n in funcs:
        ret, args = decl[n]
        call = f"drv__{n}({', '.join(arg_names(args))})"
        c.append(f"{ret} {n}({args or 'void'})")
        c.append("{")
        if ret in ("void", "vg_lite_void"):
            c += ["    g2d_hal_lock();", f"    {call};", "    g2d_hal_unlock();"]
        else:
            c += ["    g2d_hal_lock();", f"    {ret} r = {call};", "    g2d_hal_unlock();", "    return r;"]
        c += ["}", ""]
    return {"sw/driver/vg_lite/drv_api.h": "\n".join(h), "sw/driver/vg_lite/drv_api.c": "\n".join(c)}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    bad = 0
    for rel, txt in outputs().items():
        txt = spdx.add(rel, txt)
        p = ROOT / rel
        if a.check:
            if not p.exists() or p.read_text() != txt:
                print(f"gen_drv_api: {rel} missing or stale (run `make regs`)")
                bad = 1
        elif not p.exists() or p.read_text() != txt:
            p.write_text(txt)
            print(f"gen_drv_api: wrote {rel}")
    return bad


if __name__ == "__main__":
    sys.exit(main())
