"""sRGB gamma tables of the colour unit (spec/rendering.md §5.2.1, IEC 61966-2-1), v1.6b.

  LIN[c]  = round(255 * f(c / 255)),  f(s) = s / 12.92 (s <= 0.04045), ((s + 0.055) / 1.055) ** 2.4
  SRGB[c] = round(255 * g(c / 255)),  g(l) = 12.92 * l (l <= 0.0031308), 1.055 * l ** (1 / 2.4) - 0.055
  round = half up, in double.

Outputs (called by gen_regs.py, so `make regs` / `make regs-check` cover them; all generated, not committed):
  rtl/pkg/generated/g2d_gamma_pkg.sv   g2d_gamma_lin(c), g2d_gamma_srgb(c) as case tables
  sw/include/generated/g2d_gamma.h     G2D_GAMMA_LIN_INIT, G2D_GAMMA_SRGB_INIT (256 initialisers each)
"""

from __future__ import annotations

import math

BANNER = "GENERATED by scripts/gen_gamma.py from spec/rendering.md §5.2.1 -- do not edit"


def _round(x: float) -> int:
    return int(math.floor(x + 0.5))


def to_linear(s: float) -> float:
    return s / 12.92 if s <= 0.04045 else ((s + 0.055) / 1.055) ** 2.4


def to_srgb(lin: float) -> float:
    return 12.92 * lin if lin <= 0.0031308 else 1.055 * lin ** (1 / 2.4) - 0.055


LIN = [_round(255 * to_linear(c / 255)) for c in range(256)]
SRGB = [_round(255 * to_srgb(c / 255)) for c in range(256)]


def gen_sv() -> str:
    o = [f"// {BANNER}", "", "package g2d_gamma_pkg;", ""]
    for name, tab, what in (("g2d_gamma_lin", LIN, "sRGB -> linear"), ("g2d_gamma_srgb", SRGB, "linear -> sRGB")):
        o.append(f"  // {what}")
        o.append(f"  function automatic logic [7:0] {name}(logic [7:0] c);")
        o.append("    logic [7:0] v;")
        o.append("    unique case (c)")
        for c, v in enumerate(tab):
            o.append(f"      8'd{c}: v = 8'd{v};")
        o.append("    endcase")
        o.append("    return v;")
        o.append("  endfunction")
        o.append("")
    o.append("endpackage")
    o.append("")
    return "\n".join(o)


def gen_c() -> str:
    o = [f"/* {BANNER} */", "#ifndef G2D_GAMMA_H", "#define G2D_GAMMA_H", ""]
    for name, tab in (("G2D_GAMMA_LIN_INIT", LIN), ("G2D_GAMMA_SRGB_INIT", SRGB)):
        rows = [", ".join(f"{v}u" for v in tab[i:i + 16]) for i in range(0, 256, 16)]
        o.append(f"#define {name} {{ \\")
        o.extend(f"    {r}, \\" for r in rows)
        o.append("}")
        o.append("")
    o.append("#endif")
    o.append("")
    return "\n".join(o)


OUTPUTS = {
    "rtl/pkg/generated/g2d_gamma_pkg.sv": gen_sv,
    "sw/include/generated/g2d_gamma.h": gen_c,
}
