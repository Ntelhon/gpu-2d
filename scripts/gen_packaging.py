"""Generate the IP packaging files (v1.9, docs/INTEGRATION.md "Packaging") from the repository's source lists and
spec/regs.yaml:
  g2d.core              FuseSoC CAPI2 core (targets: default, xilinx, asic, lint)
  Bender.yml            Bender package (targets: default behavioural RAMs, xilinx, asic)
  ipxact/g2d_top.xml    IP-XACT (IEEE 1685-2014) component: register map, ports at the default parameters, files
They are committed (tools find them in the repository) and marked generated. `--check` exits 1 if one is stale.
Generated RTL (rtl/*/generated, rtl/wrap/generated) must exist first: `make regs`.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

BANNER = "GENERATED by scripts/gen_packaging.py. DO NOT EDIT."
PKGS = ["rtl/pkg/generated/g2d_csr_pkg.sv", "rtl/pkg/generated/g2d_state_pkg.sv", "rtl/pkg/generated/g2d_gamma_pkg.sv",
        "rtl/pkg/g2d_pkg.sv"]
DIRS = ["common", "csr", "axi", "cmdproc", "fill", "blend", "blit", "raster", "gradient", "pix", "cdc", "adapt", "top"]
RAM_BEHAV = ["rtl/common/g2d_ram_1r1w.sv", "rtl/common/g2d_ram_sp.sv"]
BUSES = ["axi", "apb", "ahb", "obi", "regintf", "wb", "tlul"]


def sources():
    out = ["rtl/csr/generated/g2d_csr_regs.sv"]
    for d in DIRS:
        out += sorted(str(p.relative_to(ROOT)) for p in (ROOT / "rtl" / d).glob("*.sv"))
    return [s for s in out if s not in RAM_BEHAV]


def wrappers():
    return [f"rtl/wrap/generated/g2d_top_{b}.sv" for b in BUSES]


def ram(impl):
    base = [f"rtl/ram/{impl}/g2d_ram_1r1w.sv", f"rtl/ram/{impl}/g2d_ram_sp.sv"]
    return base + sorted(str(p.relative_to(ROOT)) for p in (ROOT / "rtl/ram" / impl / "models").glob("*.sv"))


def regmap():
    return yaml.safe_load((ROOT / "spec/regs.yaml").read_text())


def version(m):
    v = m["version"]
    return f"{v['major']}.{v['minor']}.{v['patch']}"


# ---------------------------------------------------------------- FuseSoC

def core(m) -> str:
    v = version(m)

    def fs(name, files, ftype="systemVerilogSource", extra=""):
        lines = [f"  {name}:", "    files:"] + [f"      - {f}" for f in files] + [f"    file_type: {ftype}"]
        return "\n".join(lines) + extra

    o = ["CAPI=2:", f"# {BANNER}", f"name: ::g2d:{v}",
         "description: \"G2D 2D / 2.5D GPU IP, VGLite API compatible (docs/INTEGRATION.md). Licence: Apache-2.0 WITH SHL-2.1 (RTL), Apache-2.0 (software)\"", "",
         "filesets:",
         fs("pkgs", PKGS), fs("rtl", sources()), fs("ram_behav", RAM_BEHAV), fs("ram_xilinx", ram("xilinx")),
         fs("ram_asic", ram("asic")), fs("wrappers", wrappers()),
         fs("lint_cfg", ["rtl/lint.vlt"], "vlt"),
         fs("constraints", ["syn/constraints/g2d_top.sdc"], "SDC"), "",
         "parameters:"]
    for n, d, desc in [("DATA_W", 64, "memory port data width (64 or 128)"), ("ADDR_W", 32, "memory address width"),
                       ("CFG_ASYNC", 0, "configuration port on its own clock"),
                       ("MEM_ASYNC", 0, "memory port on its own clock")]:
        o += [f"  {n}:", "    datatype: int", f"    default: {d}", f"    description: {desc}",
              "    paramtype: vlogparam"]
    o += ["", "targets:",
          "  default: &default",
          "    filesets: [pkgs, rtl, ram_behav, wrappers]",
          "    toplevel: g2d_top",
          "    parameters: [DATA_W, ADDR_W, CFG_ASYNC, MEM_ASYNC]",
          "  xilinx:",
          "    filesets: [pkgs, rtl, ram_xilinx, wrappers]",
          "    toplevel: g2d_top",
          "    parameters: [DATA_W, ADDR_W, CFG_ASYNC, MEM_ASYNC]",
          "  asic:",
          "    filesets: [pkgs, rtl, ram_asic, wrappers, constraints]",
          "    toplevel: g2d_top",
          "    parameters: [DATA_W, ADDR_W, CFG_ASYNC, MEM_ASYNC]",
          "  lint:",
          "    <<: *default",
          "    filesets: [lint_cfg, pkgs, rtl, ram_behav, wrappers]",
          "    default_tool: verilator",
          "    tools:",
          "      verilator:",
          "        mode: lint-only",
          "        verilator_options: [-Wall]",
          ""]
    return "\n".join(o)


# ---------------------------------------------------------------- Bender

def bender(m) -> str:
    o = [f"# {BANNER}", "# Licence: Apache-2.0 WITH SHL-2.1 (RTL), Apache-2.0 (software); LICENSE", "package:", "  name: g2d", "  authors: []", "", "sources:",
         "  - files:"] + [f"      - {f}" for f in PKGS + sources() + wrappers()]
    o += ["  - target: not(any(xilinx, asic))", "    files:"] + [f"      - {f}" for f in RAM_BEHAV]
    o += ["  - target: xilinx", "    files:"] + [f"      - {f}" for f in ram("xilinx")]
    o += ["  - target: asic", "    files:"] + [f"      - {f}" for f in ram("asic")]
    return "\n".join(o) + "\n"


# ---------------------------------------------------------------- IP-XACT

PORT_RE = re.compile(r"^\s*(input|output)\s+logic\s*((?:\[[^\]]+\]\s*)*)(\w+)\s*,?")
DEFAULTS = dict(DATA_W=64, ADDR_W=32, ID_W=4, DB=8)


def ports():
    txt = re.sub(r"//[^\n]*", "", (ROOT / "rtl/top/g2d_top.sv").read_text())
    head = txt[txt.index("module g2d_top"):txt.index(");")]
    out = []
    for ln in head.splitlines():
        pm = PORT_RE.match(ln)
        if pm:
            w = pm.group(2).strip()
            if w:
                hi, lo = w[1:-1].split(":")
                hi = eval(hi, {}, dict(DEFAULTS))     # noqa: S307  (widths of our own RTL at default parameters)
                lo = eval(lo, {}, dict(DEFAULTS))     # noqa: S307
            else:
                hi = lo = None
            out.append((pm.group(1), pm.group(3), hi, lo))
    return out


ACCESS = {"rw": ("read-write", None), "ro": ("read-only", None), "const": ("read-only", None),
          "w1c": ("read-write", "oneToClear"), "wo": ("write-only", None)}


def bits(b):
    b = str(b)
    hi, lo = (b.split(":") + [b])[:2] if ":" in b else (b, b)
    return int(hi), int(lo)


def reset_value(f, m):
    r = f.get("reset", 0)
    if isinstance(r, str) and r.startswith("version."):
        return m["version"][r.split(".")[1]]
    return int(r) if r is not None else 0


def ipxact(m) -> str:
    v = version(m)
    x = ['<?xml version="1.0" encoding="UTF-8"?>', f"<!-- {BANNER} -->",
         '<ipxact:component xmlns:ipxact="http://www.accellera.org/XMLSchema/IPXACT/1685-2014"',
         '                  xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"',
         '                  xsi:schemaLocation="http://www.accellera.org/XMLSchema/IPXACT/1685-2014 '
         'http://www.accellera.org/XMLSchema/IPXACT/1685-2014/index.xsd">',
         "  <ipxact:vendor>g2d</ipxact:vendor>", "  <ipxact:library>gpu</ipxact:library>",
         "  <ipxact:name>g2d_top</ipxact:name>", f"  <ipxact:version>{v}</ipxact:version>",
         "  <ipxact:memoryMaps>", "    <ipxact:memoryMap>", "      <ipxact:name>csr</ipxact:name>",
         "      <ipxact:addressBlock>", "        <ipxact:name>g2d_csr</ipxact:name>",
         "        <ipxact:baseAddress>0</ipxact:baseAddress>", "        <ipxact:range>4096</ipxact:range>",
         "        <ipxact:width>32</ipxact:width>"]
    for r in m["blocks"]["csr"]["registers"]:
        x += ["        <ipxact:register>", f"          <ipxact:name>{r['name']}</ipxact:name>",
              f"          <ipxact:description>{escape(' '.join(str(r.get('desc', '')).split()))}</ipxact:description>",
              f"          <ipxact:addressOffset>{int(r['offset'])}</ipxact:addressOffset>",
              "          <ipxact:size>32</ipxact:size>"]
        for f in r["fields"]:
            hi, lo = bits(f["bits"])
            acc, mod = ACCESS[f.get("access", "rw")]
            x += ["          <ipxact:field>", f"            <ipxact:name>{f['name']}</ipxact:name>",
                  f"            <ipxact:bitOffset>{lo}</ipxact:bitOffset>"]
            if f.get("access") not in ("ro",):
                x += ["            <ipxact:resets>", "              <ipxact:reset>",
                      f"                <ipxact:value>{reset_value(f, m)}</ipxact:value>",
                      "              </ipxact:reset>", "            </ipxact:resets>"]
            x += [f"            <ipxact:bitWidth>{hi - lo + 1}</ipxact:bitWidth>"]
            if f.get("access") in ("ro", "w1c"):
                x += ["            <ipxact:volatile>true</ipxact:volatile>"]
            x += [f"            <ipxact:access>{acc}</ipxact:access>"]
            if mod:
                x += [f"            <ipxact:modifiedWriteValue>{mod}</ipxact:modifiedWriteValue>"]
            x += ["          </ipxact:field>"]
        x += ["        </ipxact:register>"]
    x += ["      </ipxact:addressBlock>", "      <ipxact:addressUnitBits>8</ipxact:addressUnitBits>",
          "    </ipxact:memoryMap>", "  </ipxact:memoryMaps>",
          "  <ipxact:model>", "    <ipxact:views>", "      <ipxact:view>", "        <ipxact:name>rtl</ipxact:name>",
          "        <ipxact:componentInstantiationRef>rtl</ipxact:componentInstantiationRef>", "      </ipxact:view>",
          "    </ipxact:views>", "    <ipxact:instantiations>", "      <ipxact:componentInstantiation>",
          "        <ipxact:name>rtl</ipxact:name>", "        <ipxact:language>systemverilog</ipxact:language>",
          "        <ipxact:moduleName>g2d_top</ipxact:moduleName>",
          "        <ipxact:fileSetRef><ipxact:localName>rtl</ipxact:localName></ipxact:fileSetRef>",
          "      </ipxact:componentInstantiation>", "    </ipxact:instantiations>", "    <ipxact:ports>"]
    for d, n, hi, lo in ports():
        x += ["      <ipxact:port>", f"        <ipxact:name>{n}</ipxact:name>", "        <ipxact:wire>",
              f"          <ipxact:direction>{'in' if d == 'input' else 'out'}</ipxact:direction>"]
        if hi is not None:
            x += ["          <ipxact:vectors>", "            <ipxact:vector>",
                  f"              <ipxact:left>{hi}</ipxact:left>", f"              <ipxact:right>{lo}</ipxact:right>",
                  "            </ipxact:vector>", "          </ipxact:vectors>"]
        x += ["        </ipxact:wire>", "      </ipxact:port>"]
    x += ["    </ipxact:ports>", "  </ipxact:model>", "  <ipxact:fileSets>", "    <ipxact:fileSet>",
          "      <ipxact:name>rtl</ipxact:name>"]
    for f in PKGS + sources() + RAM_BEHAV:
        x += ["      <ipxact:file>", f"        <ipxact:name>../{f}</ipxact:name>",
              "        <ipxact:fileType>systemVerilogSource</ipxact:fileType>", "      </ipxact:file>"]
    x += ["    </ipxact:fileSet>", "  </ipxact:fileSets>",
          "  <ipxact:description>G2D 2D / 2.5D GPU IP (VGLite API compatible), Apache-2.0 WITH SHL-2.1. Ports at the default parameters "
          "(DATA_W 64, ADDR_W 32, ID_W 4); see docs/INTEGRATION.md.</ipxact:description>",
          "</ipxact:component>", ""]
    return "\n".join(x)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    m = regmap()
    outs = {"g2d.core": core(m), "Bender.yml": bender(m), "ipxact/g2d_top.xml": ipxact(m)}
    bad = 0
    for rel, txt in outs.items():
        p = ROOT / rel
        if a.check:
            if not p.exists() or p.read_text() != txt:
                print(f"gen_packaging: {rel} missing or stale (run `make regs`)")
                bad = 1
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            if not p.exists() or p.read_text() != txt:
                p.write_text(txt)
                print(f"gen_packaging: wrote {rel}")
    return bad


if __name__ == "__main__":
    sys.exit(main())
