"""Generate RTL, C header and documentation from spec/regs.yaml.

Outputs (paths relative to --root):
  rtl/pkg/generated/g2d_csr_pkg.sv
  rtl/pkg/generated/g2d_state_pkg.sv
  rtl/csr/generated/g2d_csr_regs.sv
  sw/include/generated/g2d_regs.h
  docs/regs.md

Usage:
  gen_regs.py [--yaml spec/regs.yaml] [--root .]          write all outputs
  gen_regs.py --check                                     exit 1 if any output is missing or stale
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

import yaml

ACCESS_TYPES = ("rw", "ro", "const", "w1c", "wo")
BANNER = "GENERATED by scripts/gen_regs.py from spec/regs.yaml. DO NOT EDIT."
IDENT_RE = re.compile(r"^[A-Z][A-Z0-9_]*$")


class RegsError(Exception):
    """Invalid register description."""


@dataclass
class Field:
    name: str
    msb: int
    lsb: int
    access: str
    reset: int
    desc: str

    @property
    def width(self) -> int:
        return self.msb - self.lsb + 1

    @property
    def mask(self) -> int:
        return ((1 << self.width) - 1) << self.lsb


@dataclass
class Register:
    name: str
    addr: int  # byte offset (csr) or word index (state)
    desc: str
    fields: list[Field] = field(default_factory=list)

    @property
    def reset(self) -> int:
        return sum((f.reset << f.lsb) for f in self.fields)

    def has(self, *access: str) -> bool:
        return any(f.access in access for f in self.fields)


@dataclass
class RegMap:
    name: str
    version: dict
    csr_addr_bits: int
    csr: list[Register]
    state_size: int
    state: list[Register]
    # group -> (prefix, description, {name: value}); command constants, not registers
    constants: dict = field(default_factory=dict)


# --------------------------------------------------------------------------------------------
# Parsing and validation
# --------------------------------------------------------------------------------------------

def _parse_bits(text, where: str) -> tuple[int, int]:
    m = re.fullmatch(r"\s*(\d+)\s*(?::\s*(\d+)\s*)?", str(text))
    if not m:
        raise RegsError(f"{where}: bad bits '{text}' (use 'msb:lsb' or 'bit')")
    msb = int(m.group(1))
    lsb = int(m.group(2)) if m.group(2) is not None else msb
    if msb < lsb or msb > 31:
        raise RegsError(f"{where}: bits '{text}' out of range or reversed")
    return msb, lsb


def _parse_reset(value, version: dict, where: str) -> int:
    if value is None:
        return 0
    if isinstance(value, str) and value.startswith("version."):
        key = value.split(".", 1)[1]
        if key not in version:
            raise RegsError(f"{where}: unknown reset reference '{value}'")
        return int(version[key])
    if isinstance(value, bool) or not isinstance(value, int):
        raise RegsError(f"{where}: reset must be an integer, got {value!r}")
    return value


def _parse_regs(block: dict, kind: str, version: dict) -> list[Register]:
    key = "offset" if kind == "csr" else "index"
    regs: list[Register] = []
    for r in block.get("registers", []):
        rname = r.get("name", "?")
        where = f"{kind}.{rname}"
        if not IDENT_RE.match(rname):
            raise RegsError(f"{where}: register name must match {IDENT_RE.pattern}")
        if key not in r:
            raise RegsError(f"{where}: missing '{key}'")
        reg = Register(rname, int(r[key]), str(r.get("desc", "")))
        for f in r.get("fields", []):
            fname = f.get("name", "?")
            fwhere = f"{where}.{fname}"
            if not IDENT_RE.match(fname):
                raise RegsError(f"{fwhere}: field name must match {IDENT_RE.pattern}")
            msb, lsb = _parse_bits(f.get("bits"), fwhere)
            access = f.get("access", "rw" if kind == "state" else None)
            if kind == "csr" and access not in ACCESS_TYPES:
                raise RegsError(f"{fwhere}: access must be one of {ACCESS_TYPES}, got {access!r}")
            if kind == "state" and "access" in f:
                raise RegsError(f"{fwhere}: state fields take no 'access'")
            reset = _parse_reset(f.get("reset"), version, fwhere)
            if access in ("ro", "wo") and "reset" in f:
                raise RegsError(f"{fwhere}: '{access}' fields have no reset value")
            if reset < 0 or reset >= (1 << (msb - lsb + 1)):
                raise RegsError(f"{fwhere}: reset 0x{reset:x} does not fit {msb - lsb + 1} bits")
            reg.fields.append(Field(fname, msb, lsb, access, reset, str(f.get("desc", ""))))
        if not reg.fields:
            raise RegsError(f"{where}: no fields")
        _check_unique([f.name for f in reg.fields], f"{where}: duplicate field")
        used = 0
        for fl in reg.fields:
            if used & fl.mask:
                raise RegsError(f"{where}.{fl.name}: overlaps another field")
            used |= fl.mask
        regs.append(reg)
    _check_unique([r.name for r in regs], f"{kind}: duplicate register name")
    _check_unique([r.addr for r in regs], f"{kind}: duplicate {key}")
    return regs


def _check_unique(items, msg: str) -> None:
    seen = set()
    for i in items:
        if i in seen:
            raise RegsError(f"{msg} {i!r}")
        seen.add(i)


def load(path: Path) -> RegMap:
    data = yaml.safe_load(path.read_text())
    version = data.get("version", {})
    for k in ("major", "minor", "patch"):
        if not isinstance(version.get(k), int) or not 0 <= version[k] <= 255:
            raise RegsError(f"version.{k} must be an integer 0..255")
    blocks = data.get("blocks", {})
    if set(data) - {"name", "version", "blocks", "constants"}:
        raise RegsError(f"unknown top-level keys {sorted(set(data) - {'name', 'version', 'blocks', 'constants'})}")
    if set(blocks) != {"csr", "state"}:
        raise RegsError("blocks must be exactly 'csr' and 'state'")

    csr_bits = int(blocks["csr"].get("addr_bits", 12))
    csr = _parse_regs(blocks["csr"], "csr", version)
    for r in csr:
        if r.addr % 4 or r.addr >= (1 << csr_bits):
            raise RegsError(f"csr.{r.name}: offset 0x{r.addr:x} not word aligned or outside {csr_bits}-bit window")
        if r.has("wo") and r.has("w1c"):
            raise RegsError(f"csr.{r.name}: mixing 'wo' and 'w1c' fields in one register is not supported")

    state_size = int(blocks["state"].get("size", 64))
    if state_size & (state_size - 1) or not 1 <= state_size <= 256:
        raise RegsError("state.size must be a power of two in 1..256")
    state = _parse_regs(blocks["state"], "state", version)
    for r in state:
        if not 0 <= r.addr < state_size:
            raise RegsError(f"state.{r.name}: index {r.addr} outside 0..{state_size - 1}")

    csr.sort(key=lambda r: r.addr)
    state.sort(key=lambda r: r.addr)
    consts = {}
    prefixes = set()
    for g, spec in (data.get("constants") or {}).items():
        pre, vals = spec.get("prefix"), spec.get("values")
        if not isinstance(pre, str) or not re.fullmatch(r"[A-Z][A-Z0-9]*", pre) or pre in ("CSR", "ST", "FIELD"):
            raise RegsError(f"constants.{g}: prefix must be an upper-case identifier, not CSR/ST/FIELD")
        if pre in prefixes:
            raise RegsError(f"constants.{g}: prefix {pre} used twice")
        prefixes.add(pre)
        if not isinstance(vals, dict) or not vals:
            raise RegsError(f"constants.{g}: values must be a non-empty mapping")
        for k, v in vals.items():
            if not re.fullmatch(r"[A-Z][A-Z0-9_]*", str(k)) or not isinstance(v, int) or not 0 <= v < 1 << 32:
                raise RegsError(f"constants.{g}.{k}: name must be upper-case, value a 32-bit unsigned integer")
        if len(set(vals.values())) != len(vals):
            raise RegsError(f"constants.{g}: duplicate values")
        consts[g] = (pre, spec.get("desc", ""), dict(vals))
    return RegMap(data.get("name", "g2d"), version, csr_bits, csr, state_size, state, consts)


# --------------------------------------------------------------------------------------------
# SystemVerilog
# --------------------------------------------------------------------------------------------

def _lc(s: str) -> str:
    return s.lower()


def _sv_hex(width: int, value: int) -> str:
    return f"{width}'h{value:0{(width + 3) // 4}x}"


def _vec(width: int) -> str:
    return "logic" if width == 1 else f"logic [{width - 1}:0]"


def _reg2hw_fields(reg: Register) -> list[Field]:
    return [f for f in reg.fields if f.access in ("rw", "w1c", "wo")]


def _hw2reg_fields(reg: Register) -> list[Field]:
    return [f for f in reg.fields if f.access in ("ro", "w1c")]


def gen_csr_pkg(m: RegMap) -> str:
    ab = m.csr_addr_bits
    o = [f"// {BANNER}", "", "package g2d_csr_pkg;", ""]
    o.append(f"  localparam int unsigned CSR_ADDR_BITS = {ab};")
    o.append("")
    o.append("  // Bus-agnostic register interface (arch.md 4.1). One request per cycle, response same cycle.")
    o.append("  typedef struct packed {")
    o.append("    logic        valid;")
    o.append("    logic        write;")
    o.append(f"    logic [{ab - 1}:2] addr;")
    o.append("    logic [31:0] wdata;")
    o.append("    logic [3:0]  wstrb;")
    o.append("  } g2d_reg_req_t;")
    o.append("")
    o.append("  typedef struct packed {")
    o.append("    logic        ready;")
    o.append("    logic [31:0] rdata;")
    o.append("    logic        error;")
    o.append("  } g2d_reg_rsp_t;")
    o.append("")
    o.append("  // Register byte offsets")
    for r in m.csr:
        o.append(f"  localparam logic [{ab - 1}:0] G2D_CSR_{r.name}_OFFSET = {_sv_hex(ab, r.addr)};")
    o.append("")
    o.append("  // Register reset values")
    for r in m.csr:
        o.append(f"  localparam logic [31:0] G2D_CSR_{r.name}_RESET = {_sv_hex(32, r.reset)};")
    o.append("")

    # reg2hw
    o.append("  // ---- reg2hw: values driven by the register file into the design ----")
    reg2hw_regs = [r for r in m.csr if _reg2hw_fields(r)]
    for r in reg2hw_regs:
        for f in _reg2hw_fields(r):
            o.append("  typedef struct packed {")
            o.append(f"    {_vec(f.width)} q;")
            if f.access == "wo":
                o.append("    logic qe;")
            o.append(f"  }} g2d_csr_reg2hw_{_lc(r.name)}_{_lc(f.name)}_t;")
        o.append("  typedef struct packed {")
        for f in reversed(_reg2hw_fields(r)):
            o.append(f"    g2d_csr_reg2hw_{_lc(r.name)}_{_lc(f.name)}_t {_lc(f.name)};")
        o.append(f"  }} g2d_csr_reg2hw_{_lc(r.name)}_t;")
        o.append("")
    o.append("  typedef struct packed {")
    for r in reversed(reg2hw_regs):
        o.append(f"    g2d_csr_reg2hw_{_lc(r.name)}_t {_lc(r.name)};")
    o.append("  } g2d_csr_reg2hw_t;")
    o.append("")

    # hw2reg
    o.append("  // ---- hw2reg: values driven by the design into the register file ----")
    hw2reg_regs = [r for r in m.csr if _hw2reg_fields(r)]
    for r in hw2reg_regs:
        for f in _hw2reg_fields(r):
            member = "d" if f.access == "ro" else "set"
            o.append("  typedef struct packed {")
            o.append(f"    {_vec(f.width)} {member};")
            o.append(f"  }} g2d_csr_hw2reg_{_lc(r.name)}_{_lc(f.name)}_t;")
        o.append("  typedef struct packed {")
        for f in reversed(_hw2reg_fields(r)):
            o.append(f"    g2d_csr_hw2reg_{_lc(r.name)}_{_lc(f.name)}_t {_lc(f.name)};")
        o.append(f"  }} g2d_csr_hw2reg_{_lc(r.name)}_t;")
        o.append("")
    o.append("  typedef struct packed {")
    for r in reversed(hw2reg_regs):
        o.append(f"    g2d_csr_hw2reg_{_lc(r.name)}_t {_lc(r.name)};")
    o.append("  } g2d_csr_hw2reg_t;")
    o.append("")
    o.append("endpackage")
    o.append("")
    return "\n".join(o)


def gen_state_pkg(m: RegMap) -> str:
    ib = max(1, (m.state_size - 1).bit_length())
    o = [f"// {BANNER}", "", "package g2d_state_pkg;", ""]
    o.append(f"  localparam int unsigned STATE_SIZE = {m.state_size};")
    o.append(f"  localparam int unsigned STATE_IDX_BITS = {ib};")
    o.append("")
    for r in m.state:
        o.append(f"  // {r.name}: {r.desc}")
        o.append(f"  localparam logic [{ib - 1}:0] G2D_ST_{r.name} = {_sv_hex(ib, r.addr)};")
        o.append(f"  localparam logic [31:0] G2D_ST_{r.name}_RESET = {_sv_hex(32, r.reset)};")
        for f in r.fields:
            o.append(f"  localparam int unsigned G2D_ST_{r.name}_{f.name}_LSB = {f.lsb};")
            o.append(f"  localparam int unsigned G2D_ST_{r.name}_{f.name}_WIDTH = {f.width};")
        o.append("")
    o.append("  // Reset value of a state word (0 for unused indices).")
    o.append(f"  function automatic logic [31:0] g2d_state_reset(logic [{ib - 1}:0] idx);")
    o.append("    logic [31:0] v;")
    o.append("    v = '0;")
    o.append("    unique case (idx)")
    for r in m.state:
        o.append(f"      G2D_ST_{r.name}: v = G2D_ST_{r.name}_RESET;")
    o.append("      default: v = '0;")
    o.append("    endcase")
    o.append("    return v;")
    o.append("  endfunction")
    o.append("")
    o.append("  // Write mask of a state word: implemented field bits (0 for unused indices).")
    o.append(f"  function automatic logic [31:0] g2d_state_mask(logic [{ib - 1}:0] idx);")
    o.append("    logic [31:0] v;")
    o.append("    v = '0;")
    o.append("    unique case (idx)")
    for r in m.state:
        mask = sum(f.mask for f in r.fields)
        o.append(f"      G2D_ST_{r.name}: v = {_sv_hex(32, mask)};")
    o.append("      default: v = '0;")
    o.append("    endcase")
    o.append("    return v;")
    o.append("  endfunction")
    o.append("")
    o.append("endpackage")
    o.append("")
    return "\n".join(o)


def gen_csr_regs(m: RegMap) -> str:
    ab = m.csr_addr_bits
    o = [f"// {BANNER}", "//", "// CSR register file. Bus-agnostic request/response interface; the response is",
         "// combinational in the request cycle (rsp.ready = 1). Unmapped offsets return error = 1.",
         "// Writes honour byte strobes. Writes to ro/const fields are ignored.",
         "// soft_clr_i (one-cycle pulse at the end of a soft reset) returns every w1c field to its reset value.", "",
         "module g2d_csr_regs", "  import g2d_csr_pkg::*;", "(",
         "  input  logic            clk_i,",
         "  input  logic            rst_ni,",
         "  input  logic            soft_clr_i,",
         "  input  g2d_reg_req_t    req_i,",
         "  output g2d_reg_rsp_t    rsp_o,",
         "  output g2d_csr_reg2hw_t reg2hw_o,",
         "  input  g2d_csr_hw2reg_t hw2reg_i",
         ");", ""]
    o.append("  logic [31:0] wmask;")
    o.append("  logic [31:0] rdata;")
    o.append("  logic        hit;")
    o.append(f"  logic [{ab - 1}:0] addr;")
    o.append("")
    o.append("  assign addr  = {req_i.addr, 2'b00};")
    o.append("  assign wmask = {{8{req_i.wstrb[3]}}, {8{req_i.wstrb[2]}}, {8{req_i.wstrb[1]}}, {8{req_i.wstrb[0]}}};")
    o.append("")
    o.append("  // Per-register write enables")
    for r in m.csr:
        if _reg2hw_fields(r):
            o.append(f"  logic we_{_lc(r.name)};")
    for r in m.csr:
        if _reg2hw_fields(r):
            o.append(f"  assign we_{_lc(r.name)} = req_i.valid & req_i.write & (addr == G2D_CSR_{r.name}_OFFSET);")
    o.append("")

    # storage
    for r in m.csr:
        for f in r.fields:
            fn = f"{_lc(r.name)}_{_lc(f.name)}"
            w = f.width
            sl = f"{f.msb}:{f.lsb}" if w > 1 else f"{f.lsb}"
            if f.access == "rw":
                o.append(f"  // {r.name}.{f.name} (rw)")
                o.append(f"  {_vec(w)} {fn}_q;")
                o.append("  always_ff @(posedge clk_i or negedge rst_ni) begin")
                o.append("    if (!rst_ni) begin")
                o.append(f"      {fn}_q <= {_sv_hex(w, f.reset)};")
                o.append(f"    end else if (we_{_lc(r.name)}) begin")
                o.append(f"      {fn}_q <= ({fn}_q & ~wmask[{sl}]) | (req_i.wdata[{sl}] & wmask[{sl}]);")
                o.append("    end")
                o.append("  end")
                o.append(f"  assign reg2hw_o.{_lc(r.name)}.{_lc(f.name)}.q = {fn}_q;")
            elif f.access == "w1c":
                o.append(f"  // {r.name}.{f.name} (w1c, hardware set has priority over software clear)")
                o.append(f"  {_vec(w)} {fn}_q;")
                o.append(f"  {_vec(w)} {fn}_clr;")
                o.append(f"  assign {fn}_clr = we_{_lc(r.name)} ? (req_i.wdata[{sl}] & wmask[{sl}]) : '0;")
                o.append("  always_ff @(posedge clk_i or negedge rst_ni) begin")
                o.append("    if (!rst_ni) begin")
                o.append(f"      {fn}_q <= {_sv_hex(w, f.reset)};")
                o.append("    end else if (soft_clr_i) begin")
                o.append(f"      {fn}_q <= {_sv_hex(w, f.reset)};")
                o.append("    end else begin")
                o.append(f"      {fn}_q <= ({fn}_q & ~{fn}_clr) | hw2reg_i.{_lc(r.name)}.{_lc(f.name)}.set;")
                o.append("    end")
                o.append("  end")
                o.append(f"  assign reg2hw_o.{_lc(r.name)}.{_lc(f.name)}.q = {fn}_q;")
            elif f.access == "wo":
                o.append(f"  // {r.name}.{f.name} (wo: registered data plus one-cycle strobe)")
                o.append(f"  {_vec(w)} {fn}_q;")
                o.append(f"  logic {fn}_qe;")
                o.append("  always_ff @(posedge clk_i or negedge rst_ni) begin")
                o.append("    if (!rst_ni) begin")
                o.append(f"      {fn}_q  <= '0;")
                o.append(f"      {fn}_qe <= 1'b0;")
                o.append("    end else begin")
                o.append(f"      {fn}_qe <= we_{_lc(r.name)} & (|wmask[{sl}]);")
                o.append(f"      if (we_{_lc(r.name)}) begin")
                o.append(f"        {fn}_q <= req_i.wdata[{sl}] & wmask[{sl}];")
                o.append("      end")
                o.append("    end")
                o.append("  end")
                o.append(f"  assign reg2hw_o.{_lc(r.name)}.{_lc(f.name)}.q  = {fn}_q;")
                o.append(f"  assign reg2hw_o.{_lc(r.name)}.{_lc(f.name)}.qe = {fn}_qe;")
            if f.access in ("rw", "w1c", "wo"):
                o.append("")

    # read mux
    o.append("  // Read mux")
    o.append("  always_comb begin")
    o.append("    rdata = '0;")
    o.append("    hit   = 1'b1;")
    o.append("    unique case (addr)")
    for r in m.csr:
        parts = []
        for f in r.fields:
            fn = f"{_lc(r.name)}_{_lc(f.name)}"
            sl = f"{f.msb}:{f.lsb}" if f.width > 1 else f"{f.lsb}"
            if f.access in ("rw", "w1c"):
                parts.append(f"rdata[{sl}] = {fn}_q;")
            elif f.access == "ro":
                parts.append(f"rdata[{sl}] = hw2reg_i.{_lc(r.name)}.{_lc(f.name)}.d;")
            elif f.access == "const":
                parts.append(f"rdata[{sl}] = {_sv_hex(f.width, f.reset)};")
            # wo reads as 0
        o.append(f"      G2D_CSR_{r.name}_OFFSET: begin")
        for p in parts:
            o.append(f"        {p}")
        o.append("      end")
    o.append("      default: hit = 1'b0;")
    o.append("    endcase")
    o.append("  end")
    o.append("")
    o.append("  assign rsp_o.ready = 1'b1;")
    o.append("  assign rsp_o.rdata = (req_i.valid & ~req_i.write) ? rdata : '0;")
    o.append("  assign rsp_o.error = req_i.valid & ~hit;")
    o.append("")
    o.append("endmodule")
    o.append("")
    return "\n".join(o)


