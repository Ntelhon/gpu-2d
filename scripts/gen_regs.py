# Packed-struct layouts (for testbenches that see reg2hw/hw2reg as flat vectors)
# --------------------------------------------------------------------------------------------

def struct_layout(m: RegMap, which: str) -> dict[str, tuple[int, int]]:
    """Return {"<reg>.<field>.<member>": (lsb, width)} for the flat reg2hw_o / hw2reg_i vectors.

    Mirrors the member order emitted by gen_csr_pkg (first member listed = most significant).
    """
    if which == "reg2hw":
        regs = [r for r in m.csr if _reg2hw_fields(r)]
        members = lambda f: [("q", f.width)] + ([("qe", 1)] if f.access == "wo" else [])
        sel = _reg2hw_fields
    elif which == "hw2reg":
        regs = [r for r in m.csr if _hw2reg_fields(r)]
        members = lambda f: [("d" if f.access == "ro" else "set", f.width)]
        sel = _hw2reg_fields
    else:
        raise ValueError(which)
    msb_first = []
    for r in reversed(regs):
        for f in reversed(sel(r)):
            for name, width in members(f):
                msb_first.append((f"{_lc(r.name)}.{_lc(f.name)}.{name}", width))
    pos = sum(w for _, w in msb_first)
    layout = {}
    for key, width in msb_first:
        pos -= width
        layout[key] = (pos, width)
    return layout


