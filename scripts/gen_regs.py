def gen_c_header(m: RegMap) -> str:
    v = m.version
    o = ["/* SPDX-License-Identifier: Apache-2.0 OR MIT */",
         "/* Dual licence: the MIT option lets the GPL Linux driver (sw/linux) include it (LICENSE). */",
         f"/* {BANNER} */", "", "#ifndef G2D_REGS_H", "#define G2D_REGS_H", "", "#ifdef __KERNEL__", "#include <linux/types.h>   /* the Linux driver (sw/linux) */", "#else",
         "#include <stdint.h>", "#endif", ""]
    o.append(f"#define G2D_VERSION_MAJOR {v['major']}u")
    o.append(f"#define G2D_VERSION_MINOR {v['minor']}u")
    o.append(f"#define G2D_VERSION_PATCH {v['patch']}u")
    o.append("")
    o.append("/* Field helpers: G2D_FIELD_SET(G2D_CSR_STATUS_KICK_FREE, x), G2D_FIELD_GET(G2D_CSR_STATUS_KICK_FREE, reg) */")
    o.append("#define G2D_FIELD_SET(F, v) ((((uint32_t)(v)) << F##_SHIFT) & F##_MASK)")
    o.append("#define G2D_FIELD_GET(F, r) ((((uint32_t)(r)) & F##_MASK) >> F##_SHIFT)")
    o.append("")
    o.append("/* ---- CSR block: byte offsets from the AXI4-Lite base ---- */")
    for r in m.csr:
        o.append(f"#define G2D_CSR_{r.name} 0x{r.addr:03X}u /* {r.desc} */")
        o.append(f"#define G2D_CSR_{r.name}_RESET 0x{r.reset:08X}u")
        o.append(f"#define G2D_CSR_{r.name}_WMASK 0x{sum(f.mask for f in r.fields if f.access in ('rw', 'w1c', 'wo')):08X}u")
        for f in r.fields:
            o.append(f"#define G2D_CSR_{r.name}_{f.name}_SHIFT {f.lsb}u")
            o.append(f"#define G2D_CSR_{r.name}_{f.name}_MASK 0x{f.mask:08X}u")
    o.append("")
    o.append(f"/* ---- State block: LOAD_STATE word indices (size {m.state_size}) ---- */")
    o.append(f"#define G2D_ST_SIZE {m.state_size}u")
    for r in m.state:
        o.append(f"#define G2D_ST_{r.name} 0x{r.addr:02X}u /* {r.desc} */")
        o.append(f"#define G2D_ST_{r.name}_RESET 0x{r.reset:08X}u")
        o.append(f"#define G2D_ST_{r.name}_WMASK 0x{sum(f.mask for f in r.fields):08X}u")
        for f in r.fields:
            o.append(f"#define G2D_ST_{r.name}_{f.name}_SHIFT {f.lsb}u")
            o.append(f"#define G2D_ST_{r.name}_{f.name}_MASK 0x{f.mask:08X}u")
    o.append("")
    o.append("/* Index-ordered initialisers for all state words (0 for unused indices). */")
    by_idx = {r.addr: r for r in m.state}
    resets = ", ".join(f"0x{by_idx[i].reset:08X}u" if i in by_idx else "0u" for i in range(m.state_size))
    wmasks = ", ".join(f"0x{sum(f.mask for f in by_idx[i].fields):08X}u" if i in by_idx else "0u"
                       for i in range(m.state_size))
    o.append(f"#define G2D_ST_RESET_INIT {{{resets}}}")
    o.append(f"#define G2D_ST_WMASK_INIT {{{wmasks}}}")
    o.append("")
    for g, (pre, desc, vals) in m.constants.items():
        o.append(f"/* ---- {desc} ---- */")
        for k, v in vals.items():
            o.append(f"#define G2D_{pre}_{k} 0x{v:02X}u")
        o.append("")
    o.append("#endif /* G2D_REGS_H */")
    o.append("")
    return "\n".join(o)


