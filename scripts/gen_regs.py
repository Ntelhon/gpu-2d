def main(argv=None) -> int:
    here = Path(__file__).resolve().parent.parent
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--yaml", type=Path, default=here / "spec" / "regs.yaml")
    ap.add_argument("--root", type=Path, default=here)
    ap.add_argument("--check", action="store_true", help="verify outputs are up to date, write nothing")
    args = ap.parse_args(argv)

    try:
        regmap = load(args.yaml)
    except (RegsError, yaml.YAMLError) as e:
        print(f"gen_regs: error: {e}", file=sys.stderr)
        return 1

    import gen_gamma                                  # v1.6b: gamma tables of the colour unit (not from regs.yaml)
    outs = dict(outputs(regmap))
    outs.update({rel: fn() for rel, fn in gen_gamma.OUTPUTS.items()})
    import spdx                                       # licence identifier line (scripts/spdx.py)
    outs = {rel: spdx.add(rel, text) for rel, text in outs.items()}
    stale = []
    for rel, text in outs.items():
        path = args.root / rel
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(rel)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text() != text:
            path.write_text(text)
            print(f"gen_regs: wrote {rel}")
    if stale:
        print("gen_regs: stale or missing (run `make regs`): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
