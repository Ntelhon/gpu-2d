def _bits_str(f: Field) -> str:
    return f"{f.msb}:{f.lsb}" if f.width > 1 else f"{f.lsb}"


def gen_doc(m: RegMap) -> str:
    v = m.version
    o = [f"<!-- {BANNER} -->", "", "# G2D register reference", "",
         f"Version {v['major']}.{v['minor']}.{v['patch']}. Source: `spec/regs.yaml`. "
         "Access types: rw, ro (hardware status), const, w1c (write 1 to clear), wo (write-only strobe).", "",
         "## CSR block (AXI4-Lite)", "",
         "| Offset | Register | Reset | Description |", "|---|---|---|---|"]
    for r in m.csr:
        o.append(f"| 0x{r.addr:03X} | [{r.name}](#{r.name.lower()}) | 0x{r.reset:08X} | {r.desc} |")
    o.append("")
    for r in m.csr:
        o += [f"### {r.name}", "", f"Offset 0x{r.addr:03X}. {r.desc}", "",
              "| Bits | Field | Access | Reset | Description |", "|---|---|---|---|---|"]
        for f in sorted(r.fields, key=lambda f: -f.lsb):
            reset = "-" if f.access in ("ro", "wo") else f"0x{f.reset:X}"
            o.append(f"| {_bits_str(f)} | {f.name} | {f.access} | {reset} | {f.desc} |")
        o.append("")
    o += ["## State block (LOAD_STATE)", "",
          f"{m.state_size} words. Unused indices ignore writes.", "",
          "| Index | Register | Reset | Description |", "|---|---|---|---|"]
    for r in m.state:
        o.append(f"| 0x{r.addr:02X} | [{r.name}](#{r.name.lower()}) | 0x{r.reset:08X} | {r.desc} |")
    o.append("")
    for r in m.state:
        o += [f"### {r.name}", "", f"Index 0x{r.addr:02X}. {r.desc}", "",
              "| Bits | Field | Reset | Description |", "|---|---|---|---|"]
        for f in sorted(r.fields, key=lambda f: -f.lsb):
            o.append(f"| {_bits_str(f)} | {f.name} | 0x{f.reset:X} | {f.desc} |")
        o.append("")
    if m.constants:
        o += ["## Command constants", ""]
        for g, (pre, desc, vals) in m.constants.items():
            o += [f"### {g}", "", f"{desc}. C: `G2D_{pre}_<NAME>`.", "", "| Name | Value |", "|---|---|"]
            o += [f"| {k} | 0x{v:02X} |" for k, v in vals.items()]
            o.append("")
    return "\n".join(o)


