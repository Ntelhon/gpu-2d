"""Generate stubs for the vg_lite.h functions the driver does not implement (api-subset.md: anything not
listed returns VG_LITE_NOT_SUPPORT, or is a no-op where the return type is void).

    gen_vglite_stubs.py <vg_lite.h> <out.c> <driver sources...>

A function counts as implemented when a driver source defines it (`<type> vg_lite_name(...)` followed by
`{`). Output is a generated file; never edit it.
"""

import re
import sys
from pathlib import Path

PROTO = re.compile(r"(?:^|\n)[ \t]*([A-Za-z_][\w \t\*]*?)\b(vg_lite_\w+)[ \t]*\(([^;{}]*?)\)[ \t]*;", re.S)


def prototypes(header: str):
    text = re.sub(r"/\*.*?\*/", "", header, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    text = re.sub(r"^[ \t]*#[^\n]*(\\\n[^\n]*)*", "", text, flags=re.M)   # preprocessor lines
    for m in PROTO.finditer(text):
        ret, name, args = " ".join(m.group(1).split()), m.group(2), " ".join(m.group(3).split())
        if ret.startswith(("typedef", "return")) or "(" in ret:
            continue
        yield ret, name, args


def defined(sources):
    names = set()
    for src in sources:
        text = Path(src).read_text()
        names |= set(re.findall(r"\b(vg_lite_\w+)\s*\([^;{}]*\)\s*\{", text))
    return names


def stub(ret: str, name: str, args: str) -> str:
    params = [] if args in ("", "void", "vg_lite_void") else [a.strip() for a in args.split(",")]
    unused = []
    for p in params:
        m = re.search(r"(\w+)\s*(\[[^\]]*\])*\s*$", p)
        if m:
            unused.append(f"    (void){m.group(1)};")
    if ret in ("void", "vg_lite_void"):
        body = unused
    elif ret == "vg_lite_error_t":
        body = unused + ["    return VG_LITE_NOT_SUPPORT;"]
    elif ret.endswith("*"):
        body = unused + ["    return NULL;"]
    else:
        body = unused + [f"    return ({ret})0;"]
    return f"{ret} {name}({args or 'void'})\n{{\n" + "\n".join(body) + "\n}\n"


def main(argv):
    header, out, *sources = argv
    have = defined(sources)
    seen = set()
    parts = ["/* GENERATED by scripts/gen_vglite_stubs.py from vg_lite.h: functions the G2D driver does not",
             " * implement (later features, api-subset.md). Do not edit. */", "#include <stddef.h>", "",
             '#include "vg_lite.h"', ""]
    for ret, name, args in prototypes(Path(header).read_text()):
        if name in have or name in seen:
            continue
        seen.add(name)
        parts.append(stub(ret, name, args))
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    Path(out).write_text("\n".join(parts) + "\n")
    print(f"{len(seen)} stubs, {len(have)} implemented")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
