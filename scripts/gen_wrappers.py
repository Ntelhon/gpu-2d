"""Generate the per-bus top-level wrappers rtl/wrap/generated/g2d_top_<bus>.sv (v1.9, F-6, docs/INTEGRATION.md).

Each wrapper is g2d_top with its AXI4-Lite configuration port replaced by one configuration-side adapter
(rtl/adapt/g2d_<bus>2axil.sv) in the configuration-port clock domain of g2d_top: clk_cfg_i / rst_cfg_ni with
CFG_ASYNC = 1, clk_i / rst_ni with CFG_ASYNC = 0 (arch.md §2.1). Everything else (parameters, clocks, the AXI4
memory port, irq_o) is g2d_top's, unchanged. The adapter's bus ports appear as s_<bus>_<port> (ports that already
start with s_axi_ keep their name); adapter parameters appear as CFG_<name>.

Usage:
  gen_wrappers.py            write all wrappers
  gen_wrappers.py --check    exit 1 if a wrapper is missing or stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import spdx  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "rtl" / "wrap" / "generated"
BANNER = "// GENERATED by scripts/gen_wrappers.py from rtl/top/g2d_top.sv and rtl/adapt/{adapter}.sv. DO NOT EDIT."

# bus name -> (adapter module, port prefix in the wrapper)
BUSES = {
    "axi": ("g2d_axi2axil", ""),        # ports already s_axi_*
    "apb": ("g2d_apb2axil", "s_apb_"),
    "ahb": ("g2d_ahb2axil", "s_ahb_"),
    "obi": ("g2d_obi2axil", "s_obi_"),
    "regintf": ("g2d_regintf2axil", "s_"),   # ports reg_*  -> s_reg_*
    "wb": ("g2d_wb2axil", "s_"),             # ports wb_*   -> s_wb_*
    "tlul": ("g2d_tlul2axil", "s_tl_"),
}

PORT_RE = re.compile(r"^\s*(input|output)\s+logic\s*((?:\[[^\]]+\]\s*)*)(\w+)\s*,?\s*(//.*)?$")
PARAM_RE = re.compile(r"^\s*parameter\s+(.*?)\s+(\w+)\s*=\s*([^,/]+?)\s*,?\s*(//.*)?$")
LOCALPARAM_RE = re.compile(r"^\s*localparam\s+.*?\s+(\w+)\s*=")


def split_module(text: str, module: str):
    """(parameter lines, port lines) of the module header."""
    text = re.sub(r"//[^\n]*", "", text)       # comments may hold ");"
    m = re.search(rf"\bmodule\s+{module}\b", text)
    body = text[m.end():]
    end = body.index(");")
    head = body[:end]
    if head.lstrip().startswith("#"):
        pstart = head.index("#(") + 2
        depth, i = 1, pstart
        while depth:
            depth += {"(": 1, ")": -1}.get(head[i], 0)
            i += 1
        params = head[pstart:i - 1].splitlines()
        ports = head[i:].splitlines()
    else:
        params, ports = [], head.splitlines()
    return params, ports


def parse_ports(lines):
    out = []
    for ln in lines:
        pm = PORT_RE.match(ln)
        if pm:
            out.append((pm.group(1), re.sub(r"\s+", "", pm.group(2)), pm.group(3)))
    return out


def wrapper(bus: str) -> str:
    adapter, prefix = BUSES[bus]
    top_txt = (ROOT / "rtl/top/g2d_top.sv").read_text()
    ad_txt = (ROOT / "rtl/adapt" / f"{adapter}.sv").read_text()
    t_params, t_ports = split_module(top_txt, "g2d_top")
    a_params, a_ports = split_module(ad_txt, adapter)

    top_param_names, top_param_lines = [], []
    for ln in t_params:
        pm = PARAM_RE.match(ln)
        if pm:
            top_param_names.append(pm.group(2))
            top_param_lines.append(f"  parameter {pm.group(1)} {pm.group(2)} = {pm.group(3)}")
    ad_param = {}      # name -> (type, default)
    ad_local = {}
    for ln in a_params:
        pm = PARAM_RE.match(ln)
        if pm:
            ad_param[pm.group(2)] = (pm.group(1), pm.group(3))
        lm = LOCALPARAM_RE.match(ln)
        if lm:
            ad_local[lm.group(1)] = True

    def ren(width: str) -> str:
        for n in ad_param:
            width = re.sub(rf"\b{n}\b", f"CFG_{n}", width)
        if "DB" in ad_local:
            width = re.sub(r"\bDB\b", "(CFG_DATA_W/8)", width)
        return width

    def wname(p: str) -> str:
        if p.startswith("s_axi_"):
            return p
        return prefix + p

    t_ports_p = parse_ports(t_ports)
    a_ports_p = [p for p in parse_ports(a_ports) if p[2] not in ("clk_i", "rst_ni") and not p[2].startswith("m_axil_")]
    axil = [p for p in t_ports_p if p[2].startswith("s_axil_")]

    o = [BANNER.format(adapter=adapter), f"// g2d_top with the {bus.upper()} configuration port ({adapter}).", "",
         f"module g2d_top_{bus} #("]
    plines = top_param_lines + [f"  parameter {t} CFG_{n} = {d}" for n, (t, d) in ad_param.items()]
    plines.append("  localparam int unsigned DB = DATA_W / 8")
    o.append(",\n".join(plines))
    o.append(") (")
    plines = []
    for d, w, n in t_ports_p:
        if n.startswith("s_axil_"):
            if n == "s_axil_awaddr_i":   # the adapter ports go where the AXI4-Lite port was
                for ad, aw, an in a_ports_p:
                    plines.append(f"  {ad:6} logic {ren(aw):24} {wname(an)}")
            continue
        plines.append(f"  {d:6} logic {w:24} {n}")
    o.append(",\n".join(plines))
    o.append(");")
    o.append("")
    for d, w, n in axil:
        o.append(f"  logic {w:24} axil_{n[len('s_axil_'):-2]};")
    o.append("")
    o.append("  // configuration-port clock domain of g2d_top (arch.md §2.1)")
    o.append("  logic adapt_clk, adapt_rst_n;")
    o.append("  assign adapt_clk   = CFG_ASYNC ? clk_cfg_i  : clk_i;")
    o.append("  assign adapt_rst_n = CFG_ASYNC ? rst_cfg_ni : rst_ni;")
    o.append("")
    ov = ", ".join(f".{n}(CFG_{n})" for n in ad_param)
    o.append(f"  {adapter} " + (f"#({ov}) " if ov else "") + "u_adapt (")
    conns = ["    .clk_i  (adapt_clk)", "    .rst_ni (adapt_rst_n)"]
    for ad, aw, an in a_ports_p:
        conns.append(f"    .{an} ({wname(an)})")
    for d, w, n in axil:
        base = n[len("s_axil_"):-2]
        suffix = "_o" if d == "input" else "_i"      # the adapter's master side is the mirror of g2d_top's slave side
        conns.append(f"    .m_axil_{base}{suffix} (axil_{base})")
    o.append(",\n".join(conns))
    o.append("  );")
    o.append("")
    o.append("  g2d_top #(")
    o.append(",\n".join(f"    .{n}({n})" for n in top_param_names))
    o.append("  ) u_top (")
    conns = []
    for d, w, n in t_ports_p:
        if n.startswith("s_axil_"):
            conns.append(f"    .{n} (axil_{n[len('s_axil_'):-2]})")
        else:
            conns.append(f"    .{n}")
    o.append(",\n".join(conns))
    o.append("  );")
    o.append("")
    o.append("endmodule")
    return "\n".join(o) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    bad = 0
    for bus in BUSES:
        p = OUT / f"g2d_top_{bus}.sv"
        txt = spdx.add(str(p.relative_to(ROOT)), wrapper(bus))
        if a.check:
            if not p.exists() or p.read_text() != txt:
                print(f"gen_wrappers: {p.relative_to(ROOT)} missing or stale (run `make regs`)")
                bad = 1
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            if not p.exists() or p.read_text() != txt:
                p.write_text(txt)
                print(f"gen_wrappers: wrote {p.relative_to(ROOT)}")
    return bad


if __name__ == "__main__":
    sys.exit(main())
