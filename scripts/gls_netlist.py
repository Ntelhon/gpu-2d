"""Turn an IHP SG13G2 gate-level netlist of g2d_top into a Verilog model that Verilator simulates (v2.0 step C,
docs/ASIC.md "Gate-level simulation").

The PDK's standard-cell Verilog uses UDPs, which Verilator does not support. Yosys instead reads the standard cells
from their Liberty description (cell functions, flip-flops, latches), reads the netlist, flattens the cells into
logic and writes plain Verilog. The SRAM macros stay instances; the simulation links the PDK's SRAM models.

  gls_netlist.py <netlist.v> <out.v>        (YOSYS = yosys binary, default: PATH, then LibreLane's)
"""

from __future__ import annotations

import glob
import os
import shutil
import subprocess
import sys
from pathlib import Path

PDK_ROOT = Path(os.environ.get("IHP_PDK_ROOT", Path.home() / "tools/pdk/IHP-Open-PDK"))
STD_LIB = PDK_ROOT / "ihp-sg13g2/libs.ref/sg13g2_stdcell/lib/sg13g2_stdcell_typ_1p20V_25C.lib"
SRAM_LIB = PDK_ROOT / "ihp-sg13g2/libs.ref/sg13g2_sram/lib"


def yosys() -> str:
    y = os.environ.get("YOSYS") or shutil.which("yosys")
    if not y:
        # LibreLane's Yosys (Nix store), docs/TOOLS.md
        c = sorted(glob.glob("/nix/store/*-yosys-0.*/bin/yosys"))
        y = c[-1] if c else None
    if not y:
        sys.exit("error: yosys not found (set YOSYS)")
    return y


def main(argv) -> int:
    if len(argv) != 3:
        print(__doc__)
        return 2
    nl, out = Path(argv[1]), Path(argv[2])
    out.parent.mkdir(parents=True, exist_ok=True)
    # fill / decap cells have no pins in the unpowered netlist and no function: 2.6 M of them in the routed g2d_top
    # took Yosys past 10 GB. Drop them before reading.
    import re
    filler = re.compile(r"^\s*sg13g2_(fill|decap)_\d+\s+\S+\s*\(\s*\)\s*;\s*$")
    slim = out.with_suffix(".nofill.v")
    with open(nl) as fi, open(slim, "w") as fo:
        fo.writelines(l for l in fi if not filler.match(l))
    nl = slim
    srams = sorted(SRAM_LIB.glob("RM_IHPSG13_*_typ_1p20V_25C.lib"))
    script = [f"read_liberty -ignore_miss_func {STD_LIB}"]
    script += [f"read_liberty -lib {s}" for s in srams]          # macros: black boxes (PDK models in simulation)
    script += [f"read_verilog {nl}", "hierarchy -top g2d_top", "flatten", "opt_clean -purge",
               f"write_verilog -noattr {out}"]
    r = subprocess.run([yosys(), "-q", "-p", "; ".join(script)], text=True, capture_output=True)
    if r.returncode != 0:
        print(r.stdout[-4000:], r.stderr[-4000:])
        return 1
    text = out.read_text()
    out.write_text("// GENERATED by scripts/gls_netlist.py from " + nl.name + ". DO NOT EDIT.\n" + text)
    slim.unlink()
    print(f"gls_netlist: {out} ({out.stat().st_size // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
